PRAGMA journal_mode = 'mvcc';
PRAGMA mvcc_checkpoint_threshold = -1;
CREATE TABLE a(id INTEGER PRIMARY KEY, k INTEGER);
CREATE TABLE b(id INTEGER PRIMARY KEY, k INTEGER, pad TEXT);
CREATE INDEX b_k ON b(k);
WITH RECURSIVE seq(x) AS (VALUES(1) UNION ALL SELECT x+1 FROM seq WHERE x < 200000)
INSERT INTO a SELECT x, x % 100000 FROM seq;
WITH RECURSIVE seq(x) AS (VALUES(1) UNION ALL SELECT x+1 FROM seq WHERE x < 200000)
INSERT INTO b SELECT x, x % 100000, 'pad' FROM seq;
PRAGMA wal_checkpoint(TRUNCATE);
SELECT count(*) FROM a; SELECT count(*) FROM b;
