//! The operators of PostgreSQL's `pg_operator` that the frontend has.

/// A row of `pg_operator`. A type is the `oid` of its `pg_type` row, and
/// `left` is `NONE` for a prefix operator.
pub(crate) struct Operator {
    pub oid: i64,
    pub name: &'static str,
    pub left: i64,
    pub right: i64,
    pub result: i64,
    pub commutator: i64,
    pub negator: i64,
    pub can_merge: bool,
    pub can_hash: bool,
}

const NONE: i64 = 0;
const BOOL: i64 = 16;
const INT8: i64 = 20;
const INT2: i64 = 21;
const INT4: i64 = 23;
const TEXT: i64 = 25;
const FLOAT4: i64 = 700;
const FLOAT8: i64 = 701;
const DATE: i64 = 1082;
const TIMESTAMP: i64 = 1114;
const TIMESTAMPTZ: i64 = 1184;
const NUMERIC: i64 = 1700;
const UUID: i64 = 2950;

macro_rules! operators {
    ($((
        $oid:literal, $name:literal, $left:ident, $right:ident, $result:ident,
        $commutator:literal, $negator:literal, $can_merge:literal, $can_hash:literal
    ),)*) => {
        &[$(Operator {
            oid: $oid,
            name: $name,
            left: $left,
            right: $right,
            result: $result,
            commutator: $commutator,
            negator: $negator,
            can_merge: $can_merge,
            can_hash: $can_hash,
        }),*]
    };
}

