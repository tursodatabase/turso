#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_commutator_and_negator_is_a_row() {
        for row in OPERATORS {
            for oid in [row.commutator, row.negator] {
                assert!(
                    oid == NONE || OPERATORS.iter().any(|other| other.oid == oid),
                    "operator {} names the operator {oid}",
                    row.oid
                );
            }
        }
    }
}
