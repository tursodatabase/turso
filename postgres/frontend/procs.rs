//! The functions of PostgreSQL's `pg_proc` that the frontend has.

/// A row of `pg_proc`. A type is the `oid` of its `pg_type` row.
pub(crate) struct Proc {
    pub oid: i64,
    pub name: &'static str,
    pub kind: &'static str,
    pub leakproof: bool,
    pub strict: bool,
    pub returns_set: bool,
    pub volatility: &'static str,
    pub parallel: &'static str,
    pub cost: f64,
    pub rows: f64,
    pub variadic_type: i64,
    pub arg_types: &'static [i64],
    pub result: i64,
}

macro_rules! procs {
    ($((
        $oid:literal, $name:literal, $kind:literal, $leakproof:literal, $strict:literal,
        $returns_set:literal, $volatility:literal, $parallel:literal, $cost:literal,
        $rows:literal, $variadic_type:literal, $arg_types:expr, $result:literal
    ),)*) => {
        &[$(Proc {
            oid: $oid,
            name: $name,
            kind: $kind,
            leakproof: $leakproof,
            strict: $strict,
            returns_set: $returns_set,
            volatility: $volatility,
            parallel: $parallel,
            cost: $cost,
            rows: $rows,
            variadic_type: $variadic_type,
            arg_types: $arg_types,
            result: $result,
        }),*]
    };
}

