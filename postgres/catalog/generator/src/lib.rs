//! Generates the Rust tables of `turso_pg_catalog` from `postgres.bki`.
//!
//! `postgres.bki` is what PostgreSQL's `genbki.pl` writes from the catalog
//! data files of its source tree: every built-in row of every system
//! catalog, with each reference to another row already an oid and each
//! default filled in. `initdb` reads it to fill a new cluster.
//!
//! The file has one block per catalog:
//!
//! ```text
//! create pg_cast 2605
//!  (
//!  oid = oid ,
//!  castsource = oid ,
//!  castcontext = char
//!  )
//! open pg_cast
//! insert ( 10000 20 21 714 a f )
//! close pg_cast
//! ```
//!
//! A catalog that `create` marks `bootstrap` has no `open` line: its rows
//! follow the column list. The values of a row are separated by spaces.
//! `_null_` is NULL. A value with a space or punctuation is in single
//! quotes, and a quote inside it is written twice.

use std::collections::BTreeSet;
use std::fmt::Write;

/// The catalogs that get a table, in the order of the generated file. They
/// are the ones that say what a type, function, operator or cast is.
pub const CATALOGS: [&str; 14] = [
    "pg_namespace",
    "pg_type",
    "pg_range",
    "pg_collation",
    "pg_language",
    "pg_proc",
    "pg_aggregate",
    "pg_operator",
    "pg_cast",
    "pg_am",
    "pg_opfamily",
    "pg_opclass",
    "pg_amop",
    "pg_amproc",
];

/// The Rust source of the tables for [`CATALOGS`], from the text of
/// `postgres.bki`. Fails when the file has something this generator does
/// not know: a column type, a symbol or a quoting form. A new PostgreSQL
/// release then stops the generation instead of producing wrong rows.
pub fn generate(bki: &str) -> Result<String, String> {
    let catalogs = parse(bki)?;
    let mut code = String::from(HEADER);
    for name in CATALOGS {
        let catalog = catalogs
            .iter()
            .find(|catalog| catalog.name == name)
            .ok_or_else(|| format!("the file has no catalog {name}"))?;
        emit_catalog(&mut code, catalog)?;
    }
    Ok(code)
}

const HEADER: &str = "\
// @generated by turso_pg_catalog_gen from upstream/postgres.bki.
// Do not edit. To change this file, run postgres/catalog/update.sh or
// `cargo run -p turso_pg_catalog_gen`.

use crate::Oid;
";

struct Catalog {
    name: String,
    columns: Vec<Column>,
    rows: Vec<Vec<Token>>,
}

struct Column {
    name: String,
    /// The type name as the file spells it, such as `oid` or `_text`.
    bki_type: String,
    force_not_null: bool,
}

/// One value of an `insert` line.
#[derive(Clone, PartialEq)]
enum Token {
    Bare(String),
    Quoted(String),
}

impl Token {
    fn text(&self) -> &str {
        match self {
            Token::Bare(text) | Token::Quoted(text) => text,
        }
    }

    fn is_null(&self) -> bool {
        *self == Token::Bare("_null_".to_string())
    }
}

/// Reads the `create`, `open`, `insert` and `close` lines of the file.
/// The other lines declare indexes and TOAST tables, which have no rows.
fn parse(bki: &str) -> Result<Vec<Catalog>, String> {
    let mut catalogs: Vec<Catalog> = Vec::new();
    // The index in `catalogs` of the catalog that `insert` lines add to.
    let mut open: Option<usize> = None;
    let mut in_column_list = false;

    for (index, line) in bki.lines().enumerate() {
        let at = |message: String| format!("line {}: {message}", index + 1);
        let trimmed = line.trim();

        if in_column_list {
            let catalog = catalogs.last_mut().expect("a create line came first");
            match trimmed {
                "(" => {}
                ")" => in_column_list = false,
                _ => catalog.columns.push(parse_column(trimmed).map_err(at)?),
            }
            continue;
        }

        let (command, rest) = trimmed.split_once(' ').unwrap_or((trimmed, ""));
        match command {
            "create" => {
                let name = rest
                    .split(' ')
                    .next()
                    .filter(|name| !name.is_empty())
                    .ok_or_else(|| at("create has no catalog name".to_string()))?;
                catalogs.push(Catalog {
                    name: name.to_string(),
                    columns: Vec::new(),
                    rows: Vec::new(),
                });
                open = Some(catalogs.len() - 1);
                in_column_list = true;
            }
            "open" => {
                let position = catalogs
                    .iter()
                    .position(|catalog| catalog.name == rest)
                    .ok_or_else(|| at(format!("open of {rest}, which no create declared")))?;
                open = Some(position);
            }
            "close" => open = None,
            "insert" => {
                let position = open.ok_or_else(|| at("insert outside of a catalog".to_string()))?;
                let catalog = &mut catalogs[position];
                let row = parse_insert(rest).map_err(at)?;
                if row.len() != catalog.columns.len() {
                    return Err(at(format!(
                        "{} has {} columns and the row has {} values",
                        catalog.name,
                        catalog.columns.len(),
                        row.len()
                    )));
                }
                catalog.rows.push(row);
            }
            _ => {}
        }
    }
    Ok(catalogs)
}

/// Reads one line of a column list: `name = type`, then `FORCE NOT NULL`
/// or `FORCE NULL` for some columns, then a comma unless it is the last.
fn parse_column(line: &str) -> Result<Column, String> {
    let line = line.trim_end_matches(',').trim();
    let mut words = line.split_whitespace();
    let (Some(name), Some("="), Some(bki_type)) = (words.next(), words.next(), words.next()) else {
        return Err(format!("\"{line}\" is not a column"));
    };
    let force: Vec<&str> = words.collect();
    let force_not_null = match force.as_slice() {
        [] | ["FORCE", "NULL"] => false,
        ["FORCE", "NOT", "NULL"] => true,
        _ => return Err(format!("\"{line}\" has an unknown column option")),
    };
    Ok(Column {
        name: name.to_string(),
        bki_type: bki_type.to_string(),
        force_not_null,
    })
}

/// Reads the values of an `insert` line. `rest` is the line after the
/// word `insert`: the values in parentheses.
fn parse_insert(rest: &str) -> Result<Vec<Token>, String> {
    let values = rest
        .strip_prefix("( ")
        .and_then(|rest| rest.strip_suffix(" )"))
        .ok_or_else(|| "insert without ( and )".to_string())?;

    let mut tokens = Vec::new();
    let mut chars = values.chars().peekable();
    while let Some(&first) = chars.peek() {
        if first == ' ' {
            chars.next();
        } else if first == '\'' {
            chars.next();
            let mut text = String::new();
            loop {
                match chars.next() {
                    None => return Err("a quoted value does not end".to_string()),
                    Some('\'') if chars.peek() == Some(&'\'') => {
                        chars.next();
                        text.push('\'');
                    }
                    Some('\'') => break,
                    Some(other) => text.push(other),
                }
            }
            tokens.push(Token::Quoted(text));
        } else {
            let mut text = String::new();
            while let Some(&next) = chars.peek() {
                if next == ' ' {
                    break;
                }
                text.push(next);
                chars.next();
            }
            tokens.push(Token::Bare(text));
        }
    }
    Ok(tokens)
}

/// Writes the struct, the table and the lookup of one catalog.
fn emit_catalog(code: &mut String, catalog: &Catalog) -> Result<(), String> {
    let in_catalog = |message: String| format!("{}: {message}", catalog.name);

    let mut fields = Vec::new();
    for (position, column) in catalog.columns.iter().enumerate() {
        let kind = ColumnKind::of(&column.bki_type).ok_or_else(|| {
            in_catalog(format!(
                "column {} has type {}, which the generator does not know",
                column.name, column.bki_type
            ))
        })?;
        let nullable = catalog.rows.iter().any(|row| row[position].is_null());
        if nullable && column.force_not_null {
            return Err(in_catalog(format!(
                "column {} is FORCE NOT NULL and a row has NULL in it",
                column.name
            )));
        }
        fields.push(Field {
            name: &column.name,
            kind,
            nullable,
        });
    }

    // The first column is what the other catalogs refer to: `oid`, or the
    // function of a `pg_aggregate` row and the type of a `pg_range` row.
    let key = fields
        .first()
        .filter(|key| key.kind == ColumnKind::Oid && !key.nullable)
        .ok_or_else(|| in_catalog("the first column is not an oid".to_string()))?;

    let mut rows = Vec::new();
    for row in &catalog.rows {
        let key_value = oid_value(&row[0]).map_err(in_catalog)?;
        let mut literal = format!("    {} {{ ", struct_name(&catalog.name));
        for (field, token) in fields.iter().zip(row) {
            let value = field.literal(token).map_err(|message| {
                in_catalog(format!("row {key_value}, column {}: {message}", field.name))
            })?;
            write!(literal, "{}: {value}, ", field.name).expect("writing to a String");
        }
        literal.push_str("},\n");
        rows.push((key_value, literal));
    }
    rows.sort_by_key(|(key_value, _)| *key_value);
    let distinct: BTreeSet<u32> = rows.iter().map(|(key_value, _)| *key_value).collect();
    if distinct.len() != rows.len() {
        return Err(in_catalog(format!("two rows have the same {}", key.name)));
    }

    let name = &catalog.name;
    let struct_name = struct_name(name);
    let table_name = name.to_uppercase();
    let key_name = key.name;
    let row_count = rows.len();

    writeln!(code, "\n/// A row of `{name}`.").expect("writing to a String");
    code.push_str("#[derive(Debug, Clone, Copy, PartialEq)]\n");
    writeln!(code, "pub struct {struct_name} {{").expect("writing to a String");
    for field in &fields {
        writeln!(code, "    pub {}: {},", field.name, field.rust_type())
            .expect("writing to a String");
    }
    code.push_str("}\n\n");

    writeln!(
        code,
        "/// The built-in rows of `{name}`, in the order of `{key_name}`."
    )
    .expect("writing to a String");
    writeln!(
        code,
        "pub static {table_name}: [{struct_name}; {row_count}] = ["
    )
    .expect("writing to a String");
    for (_, literal) in &rows {
        code.push_str(literal);
    }
    code.push_str("];\n\n");

    writeln!(code, "impl {struct_name} {{").expect("writing to a String");
    writeln!(
        code,
        "    /// The built-in row whose `{key_name}` is `{key_name}`."
    )
    .expect("writing to a String");
    writeln!(
        code,
        "    pub fn by_{key_name}({key_name}: Oid) -> Option<&'static {struct_name}> {{"
    )
    .expect("writing to a String");
    writeln!(
        code,
        "        let position = {table_name}.binary_search_by_key(&{key_name}, |row| row.{key_name}).ok()?;"
    )
    .expect("writing to a String");
    writeln!(code, "        Some(&{table_name}[position])").expect("writing to a String");
    code.push_str("    }\n}\n");
    Ok(())
}

/// `pg_opfamily` becomes `PgOpfamily`.
fn struct_name(catalog: &str) -> String {
    catalog
        .split('_')
        .map(|word| {
            let mut letters = word.chars();
            match letters.next() {
                Some(first) => first.to_uppercase().chain(letters).collect::<String>(),
                None => String::new(),
            }
        })
        .collect()
}

struct Field<'a> {
    name: &'a str,
    kind: ColumnKind,
    /// Whether a built-in row has NULL in the column.
    nullable: bool,
}

impl Field<'_> {
    fn rust_type(&self) -> String {
        let rust_type = self.kind.rust_type();
        if self.nullable {
            format!("Option<{rust_type}>")
        } else {
            rust_type.to_string()
        }
    }

    /// The Rust expression for `token` in this column.
    fn literal(&self, token: &Token) -> Result<String, String> {
        if token.is_null() {
            return Ok("None".to_string());
        }
        let value = self.kind.literal(token)?;
        Ok(if self.nullable {
            format!("Some({value})")
        } else {
            value
        })
    }
}

/// What a column holds, which decides its Rust type.
#[derive(Clone, Copy, PartialEq)]
enum ColumnKind {
    /// An oid, or the oid of a function in a `regproc` column.
    Oid,
    Int2,
    Int4,
    Float4,
    Bool,
    /// PostgreSQL's one-byte `"char"`.
    Char,
    /// `name`, `text`, and the expression trees of `pg_node_tree`.
    Text,
    /// `oidvector`, and `_oid`, the array of oids.
    Oids,
    /// `_char`.
    Chars,
    /// `_text`, and `_aclitem`, which is kept as text.
    Texts,
}

impl ColumnKind {
    fn of(bki_type: &str) -> Option<Self> {
        Some(match bki_type {
            "oid" | "regproc" => Self::Oid,
            "int2" => Self::Int2,
            "int4" => Self::Int4,
            "float4" => Self::Float4,
            "bool" => Self::Bool,
            "char" => Self::Char,
            "name" | "text" | "pg_node_tree" => Self::Text,
            "oidvector" | "_oid" => Self::Oids,
            "_char" => Self::Chars,
            "_text" | "_aclitem" => Self::Texts,
            _ => return None,
        })
    }

    fn rust_type(self) -> &'static str {
        match self {
            Self::Oid => "Oid",
            Self::Int2 => "i16",
            Self::Int4 => "i32",
            Self::Float4 => "f32",
            Self::Bool => "bool",
            Self::Char => "char",
            Self::Text => "&'static str",
            Self::Oids => "&'static [Oid]",
            Self::Chars => "&'static [char]",
            Self::Texts => "&'static [&'static str]",
        }
    }

    /// The Rust expression for `token`, which is not NULL.
    fn literal(self, token: &Token) -> Result<String, String> {
        let text = substitute_symbol(token);
        Ok(match self {
            Self::Oid => oid_value(token)?.to_string(),
            Self::Int2 => text
                .parse::<i16>()
                .map_err(|_| format!("\"{text}\" is not an int2"))?
                .to_string(),
            Self::Int4 => text
                .parse::<i32>()
                .map_err(|_| format!("\"{text}\" is not an int4"))?
                .to_string(),
            Self::Float4 => format!(
                "{:?}",
                text.parse::<f32>()
                    .map_err(|_| format!("\"{text}\" is not a float4"))?
            ),
            Self::Bool => match text {
                "t" => "true".to_string(),
                "f" => "false".to_string(),
                _ => return Err(format!("\"{text}\" is not a bool")),
            },
            Self::Char => format!("{:?}", one_char(text)?),
            Self::Text => format!("{text:?}"),
            Self::Oids => {
                let oids = elements(token)?
                    .iter()
                    .map(|element| {
                        element
                            .parse::<u32>()
                            .map(|oid| oid.to_string())
                            .map_err(|_| format!("\"{element}\" is not an oid"))
                    })
                    .collect::<Result<Vec<_>, _>>()?;
                format!("&[{}]", oids.join(", "))
            }
            Self::Chars => {
                let chars = elements(token)?
                    .iter()
                    .map(|element| one_char(element).map(|c| format!("{c:?}")))
                    .collect::<Result<Vec<_>, _>>()?;
                format!("&[{}]", chars.join(", "))
            }
            Self::Texts => {
                let texts: Vec<String> = elements(token)?
                    .iter()
                    .map(|element| format!("{element:?}"))
                    .collect();
                format!("&[{}]", texts.join(", "))
            }
        })
    }
}

/// The oid in `token`. `-` in a function column means no function, which
/// PostgreSQL stores as oid 0.
fn oid_value(token: &Token) -> Result<u32, String> {
    match token.text() {
        "-" => Ok(0),
        text => text
            .parse()
            .map_err(|_| format!("\"{text}\" is not an oid")),
    }
}

/// The value of a symbol that `genbki.pl` leaves for `initdb` to replace,
/// as a 64-bit build of PostgreSQL replaces it. Any other token is returned
/// as it is.
fn substitute_symbol(token: &Token) -> &str {
    match token {
        Token::Bare(text) => match text.as_str() {
            "NAMEDATALEN" => "64",
            "SIZEOF_POINTER" => "8",
            "ALIGNOF_POINTER" => "d",
            "FLOAT8PASSBYVAL" => "t",
            other => other,
        },
        Token::Quoted(text) => text,
    }
}

fn one_char(text: &str) -> Result<char, String> {
    let mut chars = text.chars();
    match (chars.next(), chars.next()) {
        (Some(only), None) => Ok(only),
        _ => Err(format!("\"{text}\" is not one character")),
    }
}

/// The elements of a list value. An `oidvector` separates them with
/// spaces. An array is in braces and separates them with commas.
fn elements(token: &Token) -> Result<Vec<&str>, String> {
    let text = token.text();
    let Some(inner) = text.strip_prefix('{') else {
        return Ok(text.split_whitespace().collect());
    };
    let inner = inner
        .strip_suffix('}')
        .ok_or_else(|| format!("the array \"{text}\" does not end with }}"))?;
    // PostgreSQL quotes an array element that has a comma, a brace or a
    // space in it. No built-in row has one.
    if inner.contains(['"', '\\', '{']) {
        return Err(format!(
            "the array \"{text}\" has a quoted or nested element, which the generator does not read"
        ));
    }
    if inner.is_empty() {
        return Ok(Vec::new());
    }
    Ok(inner.split(',').collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    const SMALL: &str = "\
# PostgreSQL 18
create pg_namespace 2615
 (
 oid = oid ,
 nspname = name ,
 nspacl = _aclitem
 )
open pg_namespace
insert ( 99 pg_toast _null_ )
insert ( 11 pg_catalog '{a=b,c=d}' )
close pg_namespace
declare unique index pg_namespace_oid_index 2685 on pg_namespace using btree(oid oid_ops)
";

    #[test]
    fn rows_are_sorted_by_the_first_column_and_a_null_makes_the_column_optional() {
        let catalogs = parse(SMALL).unwrap();
        let mut code = String::new();
        emit_catalog(&mut code, &catalogs[0]).unwrap();
        assert!(code.contains("pub nspacl: Option<&'static [&'static str]>,"));
        let pg_catalog = code.find("oid: 11, nspname: \"pg_catalog\"").unwrap();
        let pg_toast = code
            .find("oid: 99, nspname: \"pg_toast\", nspacl: None")
            .unwrap();
        assert!(pg_catalog < pg_toast);
        assert!(code.contains("nspacl: Some(&[\"a=b\", \"c=d\"])"));
    }

    #[test]
    fn a_quote_inside_a_quoted_value_is_written_twice() {
        let row = parse_insert("( 100 'database''s default' '' - )").unwrap();
        let texts: Vec<&str> = row.iter().map(Token::text).collect();
        assert_eq!(texts, ["100", "database's default", "", "-"]);
        assert!(row[1] == Token::Quoted("database's default".to_string()));
    }

    #[test]
    fn a_quoted_null_word_is_text_and_not_null() {
        let row = parse_insert("( '_null_' _null_ )").unwrap();
        assert!(!row[0].is_null());
        assert!(row[1].is_null());
    }

    #[test]
    fn a_bootstrap_catalog_has_rows_without_an_open_line() {
        let bki =
            "create pg_type 1247 bootstrap rowtype_oid 71\n (\n oid = oid\n )\ninsert ( 16 )\n";
        let catalogs = parse(bki).unwrap();
        assert_eq!(catalogs[0].rows.len(), 1);
    }

    #[test]
    fn an_unknown_column_type_stops_the_generation() {
        let bki = "create pg_am 2601\n (\n oid = oid ,\n amlsn = pg_lsn\n )\nopen pg_am\ninsert ( 2 0/0 )\nclose pg_am\n";
        let catalogs = parse(bki).unwrap();
        let error = emit_catalog(&mut String::new(), &catalogs[0]).unwrap_err();
        assert_eq!(
            error,
            "pg_am: column amlsn has type pg_lsn, which the generator does not know"
        );
    }

    #[test]
    fn a_row_with_the_wrong_number_of_values_stops_the_parse() {
        let bki = "create pg_am 2601\n (\n oid = oid\n )\nopen pg_am\ninsert ( 2 3 )\n";
        let error = parse(bki).err().unwrap();
        assert_eq!(
            error,
            "line 6: pg_am has 1 columns and the row has 2 values"
        );
    }

    #[test]
    fn a_symbol_becomes_the_value_of_a_64_bit_build() {
        let bare = |text: &str| Token::Bare(text.to_string());
        assert_eq!(
            ColumnKind::Int2.literal(&bare("NAMEDATALEN")).unwrap(),
            "64"
        );
        assert_eq!(
            ColumnKind::Bool.literal(&bare("FLOAT8PASSBYVAL")).unwrap(),
            "true"
        );
        assert_eq!(
            ColumnKind::Char.literal(&bare("ALIGNOF_POINTER")).unwrap(),
            "'d'"
        );
        assert!(ColumnKind::Int4.literal(&bare("ENCODING")).is_err());
    }
}
