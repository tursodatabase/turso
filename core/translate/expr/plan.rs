/// Translate a resolved plan expression while keeping all generated bytecode
/// in the current execution region. Callers use this when a destination
/// register is reused inside a loop or coroutine.
pub fn translate_plan_expr_no_constant_opt(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    expr: &PlanExpr,
    target_register: usize,
    resolver: &Resolver<'_>,
    deopt_reason: NoConstantOptReason,
) -> Result<usize> {
    tracing::debug!(
        "translate_plan_expr_no_constant_opt: expr={expr:?}, deopt_reason={deopt_reason:?}"
    );
    let next_span = program.constant_spans_next_idx();
    let translated =
        translate_plan_expr(program, referenced_tables, expr, target_register, resolver)?;
    program.constant_spans_invalidate_after(next_span);
    Ok(translated)
}

/// Translate one resolved expression directly into VDBE bytecode.
#[turso_macros::trace_stack]
pub fn translate_plan_expr(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    expr: &PlanExpr,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let constant_span = if plan_expr_is_constant(expr)? {
        if !program.constant_span_is_open() {
            Some(program.constant_span_start())
        } else {
            None
        }
    } else {
        program.constant_span_end_all();
        None
    };

    let result =
        translate_plan_expr_inner(program, referenced_tables, expr, target_register, resolver);
    if let Some(span) = constant_span {
        program.constant_span_end(span);
    }
    result
}

fn plan_expr_is_constant(expr: &PlanExpr) -> Result<bool> {
    if !plan_expr_dependencies(expr)?.is_constant() {
        return Ok(false);
    }
    let mut deterministic = true;
    walk_plan_expr(expr, &mut |node| {
        if let PlanExpr::Function(function) = node {
            // Aggregate and window results depend on execution state even when
            // their syntax has no column arguments, such as count(*) or
            // row_number() OVER (). Hoisting their cached result-register copy
            // would read it before AggFinal/AggValue populates it.
            if plan_function_is_group_aggregate(function) || plan_function_is_window(function) {
                deterministic = false;
                return Ok(PlanWalkControl::SkipChildren);
            }
        }
        let function = match node {
            PlanExpr::Function(call) => Some(call.function.value()),
            PlanExpr::Binary {
                custom: Some(custom),
                ..
            } => Some(custom.function.value()),
            PlanExpr::Like { function, .. } => Some(function.value()),
            _ => None,
        };
        if function.is_some_and(|function| !function.is_deterministic()) {
            deterministic = false;
            return Ok(PlanWalkControl::SkipChildren);
        }
        Ok(PlanWalkControl::Continue)
    })?;
    Ok(deterministic)
}

fn translate_plan_expr_inner(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    expr: &PlanExpr,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    if let Some((register, needs_decode, collation)) = resolver.resolve_cached_plan_expr_reg(expr) {
        program.emit_insn(Insn::Copy {
            src_reg: register,
            dst_reg: target_register,
            extra_amount: 0,
        });
        if needs_decode && !program.flags.suppress_custom_type_decode() {
            emit_plan_value_decode(program, referenced_tables, expr, target_register, resolver)?;
        }
        program.set_collation(collation);
        return Ok(target_register);
    }

    if !resolver.plan_expr_reads_runtime_binding(expr)
        && try_emit_plan_expression_index_value(program, referenced_tables, expr, target_register)?
    {
        return Ok(target_register);
    }

    match expr {
        PlanExpr::Literal(literal) => emit_literal(program, literal, target_register),
        PlanExpr::Parameter(parameter) => {
            let index = program.register_plan_parameter(parameter);
            program.emit_insn(Insn::Variable {
                index,
                dest: target_register,
            });
            Ok(target_register)
        }
        PlanExpr::Column(column) => emit_plan_column(
            program,
            referenced_tables,
            column,
            target_register,
            resolver,
        ),
        PlanExpr::MergedColumn(column) => match column.value {
            PlanMergedColumnValue::Left => translate_plan_expr(
                program,
                referenced_tables,
                &column.left,
                target_register,
                resolver,
            ),
            PlanMergedColumnValue::Right => emit_plan_column(
                program,
                referenced_tables,
                &column.right,
                target_register,
                resolver,
            ),
            PlanMergedColumnValue::Coalesce => {
                let done = program.allocate_label();
                translate_plan_expr_no_constant_opt(
                    program,
                    referenced_tables,
                    &column.left,
                    target_register,
                    resolver,
                    NoConstantOptReason::RegisterReuse,
                )?;
                program.emit_insn(Insn::NotNull {
                    reg: target_register,
                    target_pc: done,
                });
                emit_plan_column(
                    program,
                    referenced_tables,
                    &column.right,
                    target_register,
                    resolver,
                )?;
                program.preassign_label_to_next_insn(done);
                Ok(target_register)
            }
        },
        PlanExpr::RowId(source) => emit_plan_rowid(
            program,
            referenced_tables,
            *source,
            target_register,
            resolver,
        ),
        PlanExpr::Output(output) => {
            let binding = resolver
                .plan_runtime_bindings()
                .output(*output)
                .cloned()
                .ok_or_else(|| {
                    LimboError::InternalError(format!(
                        "plan output {output} has no runtime binding"
                    ))
                })?;
            emit_runtime_value(program, &binding.value, target_register)
        }
        PlanExpr::Unary { operator, expr } => emit_plan_unary(
            program,
            referenced_tables,
            *operator,
            expr,
            target_register,
            resolver,
        ),
        PlanExpr::Binary {
            lhs,
            operator,
            rhs,
            custom,
        } => emit_plan_binary(
            program,
            referenced_tables,
            lhs,
            *operator,
            rhs,
            custom.as_ref(),
            target_register,
            resolver,
        ),
        PlanExpr::Between {
            expr,
            negated,
            start,
            end,
        } => emit_plan_between(
            program,
            referenced_tables,
            expr,
            *negated,
            start,
            end,
            target_register,
            resolver,
        ),
        PlanExpr::Case {
            base,
            when_then,
            else_expr,
        } => emit_plan_case(
            program,
            referenced_tables,
            base.as_deref(),
            when_then,
            else_expr.as_deref(),
            target_register,
            resolver,
        ),
        PlanExpr::Cast { expr, target } => {
            translate_plan_expr(program, referenced_tables, expr, target_register, resolver)?;
            emit_plan_cast(
                program,
                referenced_tables,
                target,
                target_register,
                resolver,
            )?;
            Ok(target_register)
        }
        PlanExpr::Collate { expr, collation } => {
            translate_plan_expr(program, referenced_tables, expr, target_register, resolver)?;
            program.set_collation(Some((*collation.value(), true)));
            Ok(target_register)
        }
        PlanExpr::Function(function) => emit_plan_function(
            program,
            referenced_tables,
            function,
            target_register,
            resolver,
        ),
        PlanExpr::IsNull(expr) => emit_plan_null_test(
            program,
            referenced_tables,
            expr,
            target_register,
            resolver,
            true,
        ),
        PlanExpr::NotNull(expr) => emit_plan_null_test(
            program,
            referenced_tables,
            expr,
            target_register,
            resolver,
            false,
        ),
        PlanExpr::InList {
            lhs,
            negated,
            values,
        } => emit_plan_in_list_value(
            program,
            referenced_tables,
            lhs,
            values,
            *negated,
            target_register,
            resolver,
        ),
        PlanExpr::Subquery(subquery) => emit_plan_subquery(
            program,
            referenced_tables,
            subquery,
            target_register,
            resolver,
        ),
        PlanExpr::Like {
            lhs,
            negated,
            operator,
            function,
            argument_count,
            rhs,
            escape,
        } => emit_plan_like(
            program,
            referenced_tables,
            lhs,
            *negated,
            *operator,
            function,
            *argument_count,
            rhs,
            escape.as_deref(),
            target_register,
            resolver,
        ),
        PlanExpr::Row(values) => {
            assert_register_range_allocated(program, target_register, values.len())?;
            for (offset, value) in values.iter().enumerate() {
                translate_plan_expr(
                    program,
                    referenced_tables,
                    value,
                    target_register + offset,
                    resolver,
                )?;
            }
            Ok(target_register)
        }
        PlanExpr::Array(values) => emit_plan_array(
            program,
            referenced_tables,
            values,
            target_register,
            resolver,
        ),
        PlanExpr::Subscript { base, index } => {
            let registers = program.alloc_registers(2);
            translate_plan_expr(program, referenced_tables, base, registers, resolver)?;
            translate_plan_expr(program, referenced_tables, index, registers + 1, resolver)?;
            program.emit_insn(Insn::ArrayElement {
                array_reg: registers,
                index_reg: registers + 1,
                dest: target_register,
            });
            Ok(target_register)
        }
        PlanExpr::FieldAccess(access) => {
            let source = program.alloc_register();
            translate_plan_expr(program, referenced_tables, &access.base, source, resolver)?;
            match access.kind {
                PlanFieldAccessKind::Struct { field_index } => {
                    program.emit_insn(Insn::StructField {
                        src_reg: source,
                        field_index,
                        dest: target_register,
                    });
                }
                PlanFieldAccessKind::Union { tag_index } => {
                    program.emit_insn(Insn::UnionExtract {
                        src_reg: source,
                        expected_tag: tag_index,
                        dest: target_register,
                    });
                }
            }
            Ok(target_register)
        }
        PlanExpr::Raise { action, message } => emit_plan_raise(
            program,
            referenced_tables,
            *action,
            message.as_deref(),
            target_register,
            resolver,
        ),
    }
}

/// Emit a condition while preserving short-circuit behavior for AND and OR.
pub fn translate_plan_condition_expr(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    expr: &PlanExpr,
    metadata: ConditionMetadata,
    resolver: &Resolver<'_>,
) -> Result<()> {
    match expr {
        PlanExpr::Binary {
            lhs,
            operator: Operator::And,
            rhs,
            ..
        } => {
            let lhs_true = program.allocate_label();
            translate_plan_condition_expr(
                program,
                referenced_tables,
                lhs,
                ConditionMetadata {
                    jump_if_condition_is_true: false,
                    jump_target_when_true: lhs_true,
                    ..metadata
                },
                resolver,
            )?;
            program.preassign_label_to_next_insn(lhs_true);
            translate_plan_condition_expr(program, referenced_tables, rhs, metadata, resolver)
        }
        PlanExpr::Binary {
            lhs,
            operator: Operator::Or,
            rhs,
            ..
        } => {
            let lhs_false = program.allocate_label();
            translate_plan_condition_expr(
                program,
                referenced_tables,
                lhs,
                ConditionMetadata {
                    jump_if_condition_is_true: true,
                    jump_target_when_false: lhs_false,
                    jump_target_when_null: lhs_false,
                    ..metadata
                },
                resolver,
            )?;
            program.preassign_label_to_next_insn(lhs_false);
            translate_plan_condition_expr(program, referenced_tables, rhs, metadata, resolver)
        }
        _ => {
            let register = program.alloc_register();
            translate_plan_expr(program, referenced_tables, expr, register, resolver)?;
            emit_cond_jump(program, metadata, register);
            Ok(())
        }
    }
}

fn emit_runtime_value(
    program: &mut ProgramBuilder,
    binding: &RuntimeValueBinding,
    target_register: usize,
) -> Result<usize> {
    match binding {
        RuntimeValueBinding::Register { register, .. } => {
            program.emit_insn(Insn::Copy {
                src_reg: *register,
                dst_reg: target_register,
                extra_amount: 0,
            });
        }
        RuntimeValueBinding::Parameter(parameter) => {
            let index = program.register_plan_parameter(parameter);
            program.emit_insn(Insn::Variable {
                index,
                dest: target_register,
            });
        }
    }
    Ok(target_register)
}

fn emit_plan_column(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    column: &PlanColumnRef,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    if let Some((register, needs_decode, collation)) =
        resolver.resolve_cached_plan_expr_reg(&PlanExpr::Column(column.clone()))
    {
        program.emit_insn(Insn::Copy {
            src_reg: register,
            dst_reg: target_register,
            extra_amount: 0,
        });
        if needs_decode && !program.flags.suppress_custom_type_decode() {
            emit_plan_column_decode(
                program,
                referenced_tables,
                column,
                target_register,
                resolver,
            )?;
        }
        program.set_collation(collation);
        return Ok(target_register);
    }

    let runtime_binding = {
        let bindings = resolver.plan_runtime_bindings();
        bindings.value(column.source, column.column).cloned()
    };
    if let Some(binding) = runtime_binding {
        let needs_decode = matches!(
            binding,
            RuntimeValueBinding::Register {
                needs_decode: true,
                ..
            }
        );
        emit_runtime_value(program, &binding, target_register)?;
        if needs_decode && !program.flags.suppress_custom_type_decode() {
            emit_plan_column_decode(
                program,
                referenced_tables,
                column,
                target_register,
                resolver,
            )?;
        }
        set_plan_column_collation(program, column);
        return Ok(target_register);
    }

    let tables = referenced_tables.ok_or_else(|| {
        LimboError::InternalError(format!(
            "plan column {}.{} has neither a runtime binding nor table references",
            column.source, column.column
        ))
    })?;
    let (is_outer, table) = tables
        .find_table_by_internal_id(column.source)
        .ok_or_else(|| {
            LimboError::InternalError(format!(
                "plan source {} is missing from table references",
                column.source
            ))
        })?;
    let read_programs = tables
        .find_source_read_programs_by_internal_id(column.source)
        .ok_or_else(|| {
            LimboError::InternalError(format!(
                "plan source {} has no read programs",
                column.source
            ))
        })?;
    let joined = tables.find_joined_table_by_internal_id(column.source);
    let has_cursor_override = program.has_cursor_override(column.source);
    let (index, index_method_column, covering) = if has_cursor_override {
        (None, None, false)
    } else if let Some(joined) = joined {
        (
            joined.op.index(),
            match &joined.op {
                Operation::IndexMethodQuery(method) => {
                    method.covered_columns.get(&column.column).copied()
                }
                _ => None,
            },
            joined.utilizes_covering_index(),
        )
    } else {
        (None, None, false)
    };

    if index_method_column.is_none() {
        set_plan_column_collation(program, column);
    }

    match table {
        Table::BTree(_) => {
            let (table_cursor, index_cursor) = if is_outer {
                if let Some(cursor) =
                    program.resolve_cursor_id_safe(&CursorKey::table(column.source))
                {
                    (Some(cursor), None)
                } else {
                    (
                        None,
                        Some(program.resolve_any_index_cursor_id_for_table(column.source)),
                    )
                }
            } else {
                let table_cursor = if index_method_column.is_some() {
                    None
                } else if covering {
                    program.resolve_cursor_id_safe(&CursorKey::table(column.source))
                } else {
                    Some(program.resolve_cursor_id(&CursorKey::table(column.source)))
                };
                let index_cursor = index.map(|index| {
                    program.resolve_cursor_id(&CursorKey::index(column.source, index.handle()))
                });
                (table_cursor, index_cursor)
            };

            let schema_column = table.columns().get(column.column).ok_or_else(|| {
                LimboError::InternalError(format!(
                    "plan source {} has no schema column {}",
                    column.source, column.column
                ))
            })?;
            let planned_generated_expr = read_programs
                .generated_expressions
                .get(column.column)
                .and_then(Option::as_ref);
            if schema_column.is_virtual_generated() && planned_generated_expr.is_none() {
                return Err(LimboError::InternalError(format!(
                    "required generated expression {}.{} was not planned by semantic analysis",
                    column.source, column.column
                )));
            }

            if let Some(index_column) = index_method_column {
                program.emit_column_or_rowid(
                    index_cursor.ok_or_else(|| {
                        LimboError::InternalError(format!(
                            "index-method source {} has no index cursor",
                            column.source
                        ))
                    })?,
                    index_column,
                    target_register,
                );
                return Ok(target_register);
            }

            if column.rowid_alias {
                if let Some(cursor) = index_cursor {
                    program.emit_insn(Insn::IdxRowId {
                        cursor_id: cursor,
                        dest: target_register,
                    });
                } else {
                    program.emit_insn(Insn::RowId {
                        cursor_id: table_cursor.ok_or_else(|| {
                            LimboError::InternalError(format!(
                                "rowid-alias source {} has no readable cursor",
                                column.source
                            ))
                        })?,
                        dest: target_register,
                    });
                }
                return Ok(target_register);
            }

            let index_is_btree = index_cursor.is_some_and(|cursor| {
                program
                    .get_cursor_type(cursor)
                    .is_some_and(|cursor_type| cursor_type.is_index())
            });
            let has_planned_generated_expr = planned_generated_expr.is_some();
            let read_from_index = if is_outer {
                index_is_btree
            } else if index_is_btree {
                index.is_some_and(|index| {
                    index.column_table_pos_to_index_pos(column.column).is_some()
                        && (!has_planned_generated_expr || covering)
                })
            } else {
                false
            };

            if has_planned_generated_expr && !read_from_index {
                let generated = planned_generated_expr.ok_or_else(|| {
                    LimboError::InternalError(format!(
                        "generated expression {}.{} disappeared",
                        column.source, column.column
                    ))
                })?;
                translate_plan_expr(
                    program,
                    referenced_tables,
                    generated,
                    target_register,
                    resolver,
                )?;
                if column.affinity != Affinity::Blob {
                    program.emit_column_affinity(target_register, column.affinity);
                }
                set_plan_column_collation(program, column);
                return Ok(target_register);
            }

            let read_cursor = if read_from_index {
                index_cursor.ok_or_else(|| {
                    LimboError::InternalError("index read has no cursor".to_string())
                })?
            } else {
                table_cursor.or(index_cursor).ok_or_else(|| {
                    LimboError::InternalError(format!(
                        "plan source {} has no readable cursor",
                        column.source
                    ))
                })?
            };
            let physical_column = if read_from_index {
                program
                    .resolve_index_for_cursor_id(read_cursor)
                    .column_table_pos_to_index_pos(column.column)
                    .ok_or_else(|| {
                        LimboError::InternalError(format!(
                            "selected index does not contain {}.{}",
                            column.source, column.column
                        ))
                    })?
            } else {
                column.column
            };
            program.emit_column_or_rowid(read_cursor, physical_column, target_register);

            if !read_from_index {
                emit_short_record_default(
                    program,
                    referenced_tables,
                    table,
                    read_programs,
                    column,
                    read_cursor,
                    target_register,
                    resolver,
                )?;
            }
            let has_column_type_programs = read_programs
                .column_type_programs
                .get(column.column)
                .ok_or_else(|| {
                    LimboError::InternalError(format!(
                        "source read programs for {} omit column {}",
                        column.source, column.column
                    ))
                })?
                .is_some();
            if !has_column_type_programs && column.affinity != Affinity::Blob {
                program.emit_column_affinity(target_register, column.affinity);
            }
            if !program.flags.suppress_custom_type_decode() {
                emit_plan_column_decode(
                    program,
                    referenced_tables,
                    column,
                    target_register,
                    resolver,
                )?;
            }
            Ok(target_register)
        }
        Table::FromClauseSubquery(subquery) => {
            if is_outer {
                if let Some(cursor) =
                    program.resolve_any_index_cursor_id_for_table_safe(column.source)
                {
                    let index = program.resolve_index_for_cursor_id(cursor);
                    let index_column = index
                        .columns
                        .iter()
                        .position(|entry| entry.pos_in_table == column.column)
                        .ok_or_else(|| {
                            LimboError::InternalError(format!(
                                "materialized subquery index omits column {}",
                                column.column
                            ))
                        })?;
                    program.emit_insn(Insn::Column {
                        cursor_id: cursor,
                        column: index_column,
                        dest: target_register,
                        default: None,
                    });
                    if column.affinity != Affinity::Blob {
                        program.emit_column_affinity(target_register, column.affinity);
                    }
                    return Ok(target_register);
                }
            }
            if let Some(joined) = joined {
                if let Operation::Search(Search::Seek {
                    index: Some(index), ..
                }) = &joined.op
                {
                    if index.ephemeral {
                        let index_column = index
                            .columns
                            .iter()
                            .position(|entry| entry.pos_in_table == column.column)
                            .ok_or_else(|| {
                                LimboError::InternalError(format!(
                                    "ephemeral subquery index omits column {}",
                                    column.column
                                ))
                            })?;
                        let cursor = program
                            .resolve_cursor_id(&CursorKey::index(column.source, index.handle()));
                        program.emit_insn(Insn::Column {
                            cursor_id: cursor,
                            column: index_column,
                            dest: target_register,
                            default: None,
                        });
                        if column.affinity != Affinity::Blob {
                            program.emit_column_affinity(target_register, column.affinity);
                        }
                        return Ok(target_register);
                    }
                }
            }
            let start = if is_outer {
                program.get_subquery_result_reg(column.source)
            } else {
                subquery.result_columns_start_reg
            }
            .ok_or_else(|| {
                LimboError::InternalError(format!(
                    "subquery source {} has no result register block",
                    column.source
                ))
            })?;
            program.emit_insn(Insn::Copy {
                src_reg: start + column.column,
                dst_reg: target_register,
                extra_amount: 0,
            });
            Ok(target_register)
        }
        Table::RecursiveCteInput(_) => {
            let cursor = program.resolve_cursor_id(&CursorKey::table(column.source));
            program.emit_insn(Insn::Column {
                cursor_id: cursor,
                column: column.column,
                dest: target_register,
                default: None,
            });
            Ok(target_register)
        }
        Table::Virtual(_) => {
            let cursor = program.resolve_cursor_id(&CursorKey::table(column.source));
            program.emit_insn(Insn::VColumn {
                cursor_id: cursor,
                column: column.column,
                dest: target_register,
            });
            Ok(target_register)
        }
    }
}

fn set_plan_column_collation(program: &mut ProgramBuilder, column: &PlanColumnRef) {
    program.set_collation(
        column
            .collation
            .as_ref()
            .map(|collation| (*collation.value(), false)),
    );
}

fn emit_short_record_default(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    table: &Table,
    read_programs: &SourceReadPrograms,
    column: &PlanColumnRef,
    cursor: usize,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    let schema_default = table
        .columns()
        .get(column.column)
        .ok_or_else(|| {
            LimboError::InternalError(format!(
                "plan source {} has no schema column {}",
                column.source, column.column
            ))
        })?
        .default
        .is_some();
    let planned_default = read_programs
        .default_expressions
        .get(column.column)
        .and_then(Option::as_ref);
    let default = match (schema_default, planned_default) {
        (false, None) => return Ok(()),
        (true, Some(default)) => default,
        (true, None) => {
            return Err(LimboError::InternalError(format!(
                "required default expression {}.{} was not planned by semantic analysis",
                column.source, column.column
            )));
        }
        (false, Some(_)) => {
            return Err(LimboError::InternalError(format!(
                "planned default expression {}.{} has no catalog default",
                column.source, column.column
            )));
        }
    };
    let type_programs = read_programs
        .column_type_programs
        .get(column.column)
        .ok_or_else(|| {
            LimboError::InternalError(format!(
                "source read programs for {} omit column {}",
                column.source, column.column
            ))
        })?
        .as_ref();
    let Some(type_programs) = type_programs else {
        return Ok(());
    };
    if type_programs.array.is_none() && type_programs.encode.is_empty() {
        return Ok(());
    }

    let done = program.allocate_label();
    program.emit_column_has_field(cursor, column.column, done);
    translate_plan_expr_no_constant_opt(
        program,
        referenced_tables,
        default,
        target_register,
        resolver,
        NoConstantOptReason::RegisterReuse,
    )?;
    emit_plan_column_value_encode(
        program,
        referenced_tables,
        type_programs,
        target_register,
        resolver,
    )?;
    program.preassign_label_to_next_insn(done);
    Ok(())
}

fn emit_plan_rowid(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    source: crate::translate::plan_expr::PlanSourceId,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    if let Some(binding) = resolver.plan_runtime_bindings().rowid(source).cloned() {
        return emit_runtime_value(program, &binding, target_register);
    }
    let tables = referenced_tables.ok_or_else(|| {
        LimboError::InternalError(format!(
            "plan rowid {source} has neither a runtime binding nor table references"
        ))
    })?;
    let (_, table) = tables
        .find_table_by_internal_id(source)
        .ok_or_else(|| LimboError::InternalError(format!("plan source {source} is missing")))?;
    let Table::BTree(table) = table else {
        crate::bail_parse_error!("no such column: rowid");
    };
    if !table.has_rowid {
        crate::bail_parse_error!("no such column: rowid");
    }
    let has_override = program.has_cursor_override(source);
    let (index, covering) = if has_override {
        (None, false)
    } else {
        tables
            .find_joined_table_by_internal_id(source)
            .map_or((None, false), |table| {
                (table.op.index(), table.utilizes_covering_index())
            })
    };
    if covering {
        let index = index.ok_or_else(|| {
            LimboError::InternalError("covering rowid read has no index".to_string())
        })?;
        let cursor = program.resolve_cursor_id(&CursorKey::index(source, index.handle()));
        program.emit_insn(Insn::IdxRowId {
            cursor_id: cursor,
            dest: target_register,
        });
    } else {
        let cursor = program.resolve_cursor_id(&CursorKey::table(source));
        program.emit_insn(Insn::RowId {
            cursor_id: cursor,
            dest: target_register,
        });
    }
    Ok(target_register)
}

fn emit_plan_unary(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    operator: UnaryOperator,
    expr: &PlanExpr,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    match operator {
        UnaryOperator::Positive => {
            translate_plan_expr(program, referenced_tables, expr, target_register, resolver)
        }
        UnaryOperator::Negative => {
            if let PlanExpr::Literal(Literal::Numeric(value)) = expr {
                let value = format!("-{value}");
                match crate::util::parse_numeric_literal(&value)? {
                    Value::Numeric(Numeric::Integer(value)) => {
                        program.emit_insn(Insn::Integer {
                            value,
                            dest: target_register,
                        });
                    }
                    Value::Numeric(Numeric::Float(value)) => {
                        program.emit_insn(Insn::Real {
                            value: value.into(),
                            dest: target_register,
                        });
                    }
                    _ => unreachable!("numeric literal parser returned a non-numeric value"),
                }
            } else {
                let source = program.alloc_register();
                translate_plan_expr(program, referenced_tables, expr, source, resolver)?;
                let zero = program.alloc_register();
                program.emit_insn(Insn::Integer {
                    value: 0,
                    dest: zero,
                });
                program.mark_last_insn_constant();
                program.emit_insn(Insn::Subtract {
                    lhs: zero,
                    rhs: source,
                    dest: target_register,
                });
            }
            Ok(target_register)
        }
        UnaryOperator::BitwiseNot => {
            let source = program.alloc_register();
            translate_plan_expr(program, referenced_tables, expr, source, resolver)?;
            program.emit_insn(Insn::BitNot {
                reg: source,
                dest: target_register,
            });
            Ok(target_register)
        }
        UnaryOperator::Not => {
            let source = program.alloc_register();
            translate_plan_expr(program, referenced_tables, expr, source, resolver)?;
            program.emit_insn(Insn::Not {
                reg: source,
                dest: target_register,
            });
            Ok(target_register)
        }
    }
}

fn emit_plan_null_test(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    expr: &PlanExpr,
    target_register: usize,
    resolver: &Resolver<'_>,
    is_null: bool,
) -> Result<usize> {
    let source = program.alloc_register();
    translate_plan_expr(program, referenced_tables, expr, source, resolver)?;
    program.emit_insn(Insn::Integer {
        value: 1,
        dest: target_register,
    });
    let done = program.allocate_label();
    program.emit_insn(if is_null {
        Insn::IsNull {
            reg: source,
            target_pc: done,
        }
    } else {
        Insn::NotNull {
            reg: source,
            target_pc: done,
        }
    });
    program.emit_insn(Insn::Integer {
        value: 0,
        dest: target_register,
    });
    program.preassign_label_to_next_insn(done);
    Ok(target_register)
}

fn emit_plan_array(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    values: &[PlanExpr],
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let start = program.alloc_registers(values.len());
    for (offset, value) in values.iter().enumerate() {
        translate_plan_expr(program, referenced_tables, value, start + offset, resolver)?;
    }
    program.emit_insn(Insn::MakeArray {
        start_reg: start,
        count: values.len(),
        dest: target_register,
    });
    Ok(target_register)
}

fn emit_plan_raise(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    action: ResolveType,
    message: Option<&PlanExpr>,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let in_trigger = program.trigger.is_some();
    match action {
        ResolveType::Ignore => {
            if !in_trigger {
                crate::bail_parse_error!("RAISE() may only be used within a trigger-program");
            }
            program.emit_insn(Insn::Halt {
                err_code: 0,
                description: String::new(),
                on_error: Some(ResolveType::Ignore),
                description_reg: None,
            });
        }
        ResolveType::Fail | ResolveType::Abort | ResolveType::Rollback => {
            if !in_trigger && action != ResolveType::Abort {
                crate::bail_parse_error!("RAISE() may only be used within a trigger-program");
            }
            let message = message.ok_or_else(|| {
                LimboError::ParseError("RAISE requires an error message".to_string())
            })?;
            let error_code = if in_trigger {
                SQLITE_CONSTRAINT_TRIGGER
            } else {
                SQLITE_ERROR
            };
            if let PlanExpr::Literal(Literal::String(message)) = message {
                program.emit_insn(Insn::Halt {
                    err_code: error_code,
                    description: super::sanitize_string(message),
                    on_error: Some(action),
                    description_reg: None,
                });
            } else {
                let message_register = program.alloc_register();
                translate_plan_expr(
                    program,
                    referenced_tables,
                    message,
                    message_register,
                    resolver,
                )?;
                program.emit_insn(Insn::Halt {
                    err_code: error_code,
                    description: String::new(),
                    on_error: Some(action),
                    description_reg: Some(message_register),
                });
            }
        }
        ResolveType::Replace => crate::bail_parse_error!("REPLACE is not valid for RAISE"),
    }
    Ok(target_register)
}

fn emit_plan_binary(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    lhs: &PlanExpr,
    operator: Operator,
    rhs: &PlanExpr,
    custom: Option<&PlanCustomBinaryOperator>,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    if let Some(custom) = custom {
        return emit_plan_custom_binary(
            program,
            referenced_tables,
            lhs,
            rhs,
            custom,
            target_register,
            resolver,
        );
    }
    if let Some((is_not, is_true)) = match (operator, rhs) {
        (Operator::Is, PlanExpr::Literal(Literal::True)) => Some((false, true)),
        (Operator::Is, PlanExpr::Literal(Literal::False)) => Some((false, false)),
        (Operator::IsNot, PlanExpr::Literal(Literal::True)) => Some((true, true)),
        (Operator::IsNot, PlanExpr::Literal(Literal::False)) => Some((true, false)),
        _ => None,
    } {
        let source = program.alloc_register();
        translate_plan_expr(program, referenced_tables, lhs, source, resolver)?;
        program.emit_insn(Insn::IsTrue {
            reg: source,
            dest: target_register,
            null_value: is_not,
            invert: is_not == is_true,
        });
        return Ok(target_register);
    }

    let (lhs_width, rhs_width) = {
        let facts = resolver.plan_runtime_bindings();
        (
            plan_expr_vector_size(lhs, &*facts)?,
            plan_expr_vector_size(rhs, &*facts)?,
        )
    };
    if lhs_width != rhs_width {
        crate::bail_parse_error!("row value misused");
    }
    if lhs_width > 1 {
        if !matches!(
            operator,
            Operator::Equals
                | Operator::NotEquals
                | Operator::Less
                | Operator::LessEquals
                | Operator::Greater
                | Operator::GreaterEquals
                | Operator::Is
                | Operator::IsNot
        ) {
            crate::bail_parse_error!("row value misused");
        }
        let lhs_register = program.alloc_registers(lhs_width);
        let rhs_register = program.alloc_registers(rhs_width);
        translate_plan_expr(program, referenced_tables, lhs, lhs_register, resolver)?;
        translate_plan_expr(program, referenced_tables, rhs, rhs_register, resolver)?;
        emit_plan_row_comparison(
            program,
            lhs,
            rhs,
            operator,
            lhs_register,
            rhs_register,
            lhs_width,
            target_register,
            resolver,
        )?;
        return Ok(target_register);
    }

    let (lhs_register, rhs_register) = if plan_exprs_are_equivalent(lhs, rhs) {
        let shared = program.alloc_register();
        translate_plan_expr(program, referenced_tables, lhs, shared, resolver)?;
        (shared, shared)
    } else {
        let registers = program.alloc_registers(2);
        translate_plan_expr(program, referenced_tables, lhs, registers, resolver)?;
        program.reset_collation();
        translate_plan_expr(program, referenced_tables, rhs, registers + 1, resolver)?;
        program.reset_collation();
        (registers, registers + 1)
    };
    emit_plan_binary_insn(
        program,
        lhs,
        rhs,
        operator,
        lhs_register,
        rhs_register,
        target_register,
        resolver,
    )?;
    if operator.is_comparison() {
        program.reset_collation();
    }
    Ok(target_register)
}

fn emit_plan_custom_binary(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    lhs: &PlanExpr,
    rhs: &PlanExpr,
    custom: &PlanCustomBinaryOperator,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let values = program.alloc_registers(2);
    translate_plan_expr(program, referenced_tables, lhs, values, resolver)?;
    translate_plan_expr(program, referenced_tables, rhs, values + 1, resolver)?;

    if let Some(encoding) = &custom.literal_encoding {
        let value_register = match encoding.operand {
            PlanBinaryOperand::Left => values,
            PlanBinaryOperand::Right => values + 1,
        };
        if let Some(encoder) = &encoding.encoder {
            emit_plan_schema_call(
                program,
                referenced_tables,
                encoder,
                value_register,
                value_register,
                resolver,
            )?;
        }
    }

    let arguments = program.alloc_registers(2);
    let (first, second) = if custom.swap_args {
        (values + 1, values)
    } else {
        (values, values + 1)
    };
    program.emit_insn(Insn::Copy {
        src_reg: first,
        dst_reg: arguments,
        extra_amount: 0,
    });
    program.emit_insn(Insn::Copy {
        src_reg: second,
        dst_reg: arguments + 1,
        extra_amount: 0,
    });
    program.emit_insn(Insn::Function {
        constant_mask: 0,
        start_reg: arguments,
        dest: target_register,
        func: FuncCtx {
            func: custom.function.value().clone(),
            arg_count: 2,
        },
    });
    if custom.negate {
        program.emit_insn(Insn::Not {
            reg: target_register,
            dest: target_register,
        });
    }
    Ok(target_register)
}

#[allow(clippy::too_many_arguments)]
fn emit_plan_binary_insn(
    program: &mut ProgramBuilder,
    lhs_expr: &PlanExpr,
    rhs_expr: &PlanExpr,
    operator: Operator,
    lhs: usize,
    rhs: usize,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    let facts = resolver.plan_runtime_bindings();
    let affinity = if operator.is_comparison() {
        resolve_plan_comparison_affinity(lhs_expr, rhs_expr, &*facts)
    } else {
        Affinity::Blob
    };
    let collation = if operator.is_comparison() {
        Some(resolve_plan_comparison_collation(
            lhs_expr, rhs_expr, &*facts,
        )?)
    } else {
        None
    };
    let array_comparison =
        plan_expr_is_array(lhs_expr, &*facts) && plan_expr_is_array(rhs_expr, &*facts);
    drop(facts);
    let comparison_flags = || {
        let flags = CmpInsFlags::default().with_affinity(affinity);
        if array_comparison {
            flags.array_cmp()
        } else {
            flags
        }
    };

    match operator {
        Operator::NotEquals
        | Operator::Equals
        | Operator::Less
        | Operator::LessEquals
        | Operator::Greater
        | Operator::GreaterEquals => {
            let if_true = program.allocate_label();
            let instruction = match operator {
                Operator::NotEquals => Insn::Ne {
                    lhs,
                    rhs,
                    target_pc: if_true,
                    flags: comparison_flags(),
                    collation,
                },
                Operator::Equals => Insn::Eq {
                    lhs,
                    rhs,
                    target_pc: if_true,
                    flags: comparison_flags(),
                    collation,
                },
                Operator::Less => Insn::Lt {
                    lhs,
                    rhs,
                    target_pc: if_true,
                    flags: comparison_flags(),
                    collation,
                },
                Operator::LessEquals => Insn::Le {
                    lhs,
                    rhs,
                    target_pc: if_true,
                    flags: comparison_flags(),
                    collation,
                },
                Operator::Greater => Insn::Gt {
                    lhs,
                    rhs,
                    target_pc: if_true,
                    flags: comparison_flags(),
                    collation,
                },
                Operator::GreaterEquals => Insn::Ge {
                    lhs,
                    rhs,
                    target_pc: if_true,
                    flags: comparison_flags(),
                    collation,
                },
                _ => unreachable!(),
            };
            wrap_eval_jump_expr_zero_or_null(
                program,
                instruction,
                target_register,
                if_true,
                lhs,
                rhs,
            );
        }
        Operator::Is | Operator::IsNot => {
            let if_true = program.allocate_label();
            let flags = CmpInsFlags::default().null_eq().with_affinity(affinity);
            let instruction = if operator == Operator::Is {
                Insn::Eq {
                    lhs,
                    rhs,
                    target_pc: if_true,
                    flags,
                    collation,
                }
            } else {
                Insn::Ne {
                    lhs,
                    rhs,
                    target_pc: if_true,
                    flags,
                    collation,
                }
            };
            wrap_eval_jump_expr(program, instruction, target_register, if_true);
        }
        Operator::Add => program.emit_insn(Insn::Add {
            lhs,
            rhs,
            dest: target_register,
        }),
        Operator::Subtract => program.emit_insn(Insn::Subtract {
            lhs,
            rhs,
            dest: target_register,
        }),
        Operator::Multiply => program.emit_insn(Insn::Multiply {
            lhs,
            rhs,
            dest: target_register,
        }),
        Operator::Divide => program.emit_insn(Insn::Divide {
            lhs,
            rhs,
            dest: target_register,
        }),
        Operator::Modulus => program.emit_insn(Insn::Remainder {
            lhs,
            rhs,
            dest: target_register,
        }),
        Operator::And => program.emit_insn(Insn::And {
            lhs,
            rhs,
            dest: target_register,
        }),
        Operator::Or => program.emit_insn(Insn::Or {
            lhs,
            rhs,
            dest: target_register,
        }),
        Operator::BitwiseAnd => program.emit_insn(Insn::BitAnd {
            lhs,
            rhs,
            dest: target_register,
        }),
        Operator::BitwiseOr => program.emit_insn(Insn::BitOr {
            lhs,
            rhs,
            dest: target_register,
        }),
        Operator::RightShift => program.emit_insn(Insn::ShiftRight {
            lhs,
            rhs,
            dest: target_register,
        }),
        Operator::LeftShift => program.emit_insn(Insn::ShiftLeft {
            lhs,
            rhs,
            dest: target_register,
        }),
        #[cfg(feature = "json")]
        Operator::ArrowRight | Operator::ArrowRightShift => {
            use crate::function::JsonFunc;
            let function = if operator == Operator::ArrowRight {
                JsonFunc::JsonArrowExtract
            } else {
                JsonFunc::JsonArrowShiftExtract
            };
            program.emit_insn(Insn::Function {
                constant_mask: 0,
                start_reg: lhs,
                dest: target_register,
                func: FuncCtx {
                    func: Func::Json(function),
                    arg_count: 2,
                },
            });
        }
        #[cfg(not(feature = "json"))]
        Operator::ArrowRight | Operator::ArrowRightShift => {
            crate::bail_parse_error!("JSON operators require the json feature");
        }
        Operator::Concat => {
            let facts = resolver.plan_runtime_bindings();
            if plan_expr_is_array(lhs_expr, &*facts) || plan_expr_is_array(rhs_expr, &*facts) {
                program.emit_insn(Insn::ArrayConcat {
                    lhs,
                    rhs,
                    dest: target_register,
                });
            } else {
                program.emit_insn(Insn::Concat {
                    lhs,
                    rhs,
                    dest: target_register,
                });
            }
        }
        Operator::ArrayContains | Operator::ArrayOverlap => {
            resolver.require_custom_types("Array features")?;
            let start = if rhs == lhs + 1 {
                lhs
            } else {
                let registers = program.alloc_registers(2);
                program.emit_insn(Insn::Copy {
                    src_reg: lhs,
                    dst_reg: registers,
                    extra_amount: 0,
                });
                program.emit_insn(Insn::Copy {
                    src_reg: rhs,
                    dst_reg: registers + 1,
                    extra_amount: 0,
                });
                registers
            };
            let function = if operator == Operator::ArrayContains {
                ScalarFunc::ArrayContainsAll
            } else {
                ScalarFunc::ArrayOverlap
            };
            program.emit_insn(Insn::Function {
                constant_mask: 0,
                start_reg: start,
                dest: target_register,
                func: FuncCtx {
                    func: Func::Scalar(function),
                    arg_count: 2,
                },
            });
        }
        Operator::BitwiseNot => {
            return Err(LimboError::InternalError(
                "binary bitwise-not reached PlanExpr emission".to_string(),
            ));
        }
    }
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn emit_plan_row_comparison(
    program: &mut ProgramBuilder,
    lhs_expr: &PlanExpr,
    rhs_expr: &PlanExpr,
    operator: Operator,
    lhs_start: usize,
    rhs_start: usize,
    width: usize,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    let null_equal = matches!(operator, Operator::Is | Operator::IsNot);
    let equality = matches!(
        operator,
        Operator::Equals | Operator::NotEquals | Operator::Is | Operator::IsNot
    );
    if equality {
        let null_seen = (!null_equal).then(|| {
            let register = program.alloc_register();
            program.emit_insn(Insn::Integer {
                value: 0,
                dest: register,
            });
            register
        });
        let done = program.allocate_label();
        for index in 0..width {
            let next = program.allocate_label();
            let (affinity, collation) =
                plan_row_component_comparison(lhs_expr, rhs_expr, index, resolver)?;
            program.emit_insn(Insn::Eq {
                lhs: lhs_start + index,
                rhs: rhs_start + index,
                target_pc: next,
                flags: if null_equal {
                    CmpInsFlags::default().null_eq().with_affinity(affinity)
                } else {
                    CmpInsFlags::default().with_affinity(affinity)
                },
                collation: Some(collation),
            });
            if null_equal {
                program.emit_insn(Insn::Integer {
                    value: 0,
                    dest: target_register,
                });
                program.emit_insn(Insn::Goto { target_pc: done });
            } else {
                let mark_null = program.allocate_label();
                program.emit_insn(Insn::IsNull {
                    reg: lhs_start + index,
                    target_pc: mark_null,
                });
                program.emit_insn(Insn::IsNull {
                    reg: rhs_start + index,
                    target_pc: mark_null,
                });
                program.emit_insn(Insn::Integer {
                    value: 0,
                    dest: target_register,
                });
                program.emit_insn(Insn::Goto { target_pc: done });
                program.preassign_label_to_next_insn(mark_null);
                program.emit_insn(Insn::Integer {
                    value: 1,
                    dest: null_seen.expect("null register exists"),
                });
            }
            program.preassign_label_to_next_insn(next);
        }
        program.emit_insn(Insn::Integer {
            value: 1,
            dest: target_register,
        });
        if let Some(null_seen) = null_seen {
            let no_null = program.allocate_label();
            program.emit_insn(Insn::IfNot {
                reg: null_seen,
                target_pc: no_null,
                jump_if_null: true,
            });
            program.emit_insn(Insn::Null {
                dest: target_register,
                dest_end: None,
            });
            program.preassign_label_to_next_insn(no_null);
        }
        program.preassign_label_to_next_insn(done);
        if matches!(operator, Operator::NotEquals | Operator::IsNot) {
            invert_boolean_register(program, target_register);
        }
        return Ok(());
    }

    let done = program.allocate_label();
    let null_result = program.allocate_label();
    for index in 0..width {
        let next = program.allocate_label();
        let (affinity, collation) =
            plan_row_component_comparison(lhs_expr, rhs_expr, index, resolver)?;
        let lhs = lhs_start + index;
        let rhs = rhs_start + index;
        program.emit_insn(Insn::IsNull {
            reg: lhs,
            target_pc: null_result,
        });
        program.emit_insn(Insn::IsNull {
            reg: rhs,
            target_pc: null_result,
        });
        program.emit_insn(Insn::Eq {
            lhs,
            rhs,
            target_pc: next,
            flags: CmpInsFlags::default().with_affinity(affinity),
            collation: Some(collation),
        });
        let true_label = program.allocate_label();
        let order_is_less = matches!(operator, Operator::Less | Operator::LessEquals);
        program.emit_insn(if order_is_less {
            Insn::Lt {
                lhs,
                rhs,
                target_pc: true_label,
                flags: CmpInsFlags::default().with_affinity(affinity),
                collation: Some(collation),
            }
        } else {
            Insn::Gt {
                lhs,
                rhs,
                target_pc: true_label,
                flags: CmpInsFlags::default().with_affinity(affinity),
                collation: Some(collation),
            }
        });
        program.emit_insn(Insn::Integer {
            value: 0,
            dest: target_register,
        });
        program.emit_insn(Insn::Goto { target_pc: done });
        program.preassign_label_to_next_insn(true_label);
        program.emit_insn(Insn::Integer {
            value: 1,
            dest: target_register,
        });
        program.emit_insn(Insn::Goto { target_pc: done });
        program.preassign_label_to_next_insn(next);
    }
    program.emit_insn(Insn::Integer {
        value: i64::from(matches!(
            operator,
            Operator::LessEquals | Operator::GreaterEquals
        )),
        dest: target_register,
    });
    program.emit_insn(Insn::Goto { target_pc: done });
    program.preassign_label_to_next_insn(null_result);
    program.emit_insn(Insn::Null {
        dest: target_register,
        dest_end: None,
    });
    program.preassign_label_to_next_insn(done);
    Ok(())
}

fn plan_row_component_comparison(
    lhs: &PlanExpr,
    rhs: &PlanExpr,
    index: usize,
    resolver: &Resolver<'_>,
) -> Result<(Affinity, crate::translate::collate::CollationSeq)> {
    let lhs = match lhs {
        PlanExpr::Row(values) => values.get(index).unwrap_or(lhs),
        _ => lhs,
    };
    let rhs = match rhs {
        PlanExpr::Row(values) => values.get(index).unwrap_or(rhs),
        _ => rhs,
    };
    let facts = resolver.plan_runtime_bindings();
    Ok((
        resolve_plan_comparison_affinity(lhs, rhs, &*facts),
        resolve_plan_comparison_collation(lhs, rhs, &*facts)?,
    ))
}

#[allow(clippy::too_many_arguments)]
fn emit_plan_between(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    expr: &PlanExpr,
    negated: bool,
    start: &PlanExpr,
    end: &PlanExpr,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let value_register = program.alloc_register();
    translate_plan_expr(program, referenced_tables, expr, value_register, resolver)?;
    let bounds = program.alloc_registers(2);
    translate_plan_expr(program, referenced_tables, start, bounds, resolver)?;
    translate_plan_expr(program, referenced_tables, end, bounds + 1, resolver)?;
    let comparisons = program.alloc_registers(2);
    let (lower, upper, combine) = if negated {
        (Operator::Less, Operator::Greater, Operator::Or)
    } else {
        (Operator::GreaterEquals, Operator::LessEquals, Operator::And)
    };
    emit_plan_binary_insn(
        program,
        expr,
        start,
        lower,
        value_register,
        bounds,
        comparisons,
        resolver,
    )?;
    emit_plan_binary_insn(
        program,
        expr,
        end,
        upper,
        value_register,
        bounds + 1,
        comparisons + 1,
        resolver,
    )?;
    program.emit_insn(if combine == Operator::And {
        Insn::And {
            lhs: comparisons,
            rhs: comparisons + 1,
            dest: target_register,
        }
    } else {
        Insn::Or {
            lhs: comparisons,
            rhs: comparisons + 1,
            dest: target_register,
        }
    });
    Ok(target_register)
}

#[allow(clippy::too_many_arguments)]
fn emit_plan_case(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    base: Option<&PlanExpr>,
    when_then: &[(PlanExpr, PlanExpr)],
    else_expr: Option<&PlanExpr>,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let done = program.allocate_label();
    let base_register = if let Some(base) = base {
        let register = program.alloc_register();
        translate_plan_expr(program, referenced_tables, base, register, resolver)?;
        Some((base, register))
    } else {
        None
    };
    let when_register = program.alloc_register();
    for (when, then) in when_then {
        let next = program.allocate_label();
        translate_plan_expr_no_constant_opt(
            program,
            referenced_tables,
            when,
            when_register,
            resolver,
            NoConstantOptReason::RegisterReuse,
        )?;
        if let Some((base_expr, base_register)) = base_register {
            let facts = resolver.plan_runtime_bindings();
            let affinity = resolve_plan_comparison_affinity(base_expr, when, &*facts);
            let collation = resolve_plan_comparison_collation(base_expr, when, &*facts)?;
            drop(facts);
            program.emit_insn(Insn::Ne {
                lhs: base_register,
                rhs: when_register,
                target_pc: next,
                flags: CmpInsFlags::default()
                    .jump_if_null()
                    .with_affinity(affinity),
                collation: Some(collation),
            });
        } else {
            program.emit_insn(Insn::IfNot {
                reg: when_register,
                target_pc: next,
                jump_if_null: true,
            });
        }
        translate_plan_expr_no_constant_opt(
            program,
            referenced_tables,
            then,
            target_register,
            resolver,
            NoConstantOptReason::RegisterReuse,
        )?;
        program.emit_insn(Insn::Goto { target_pc: done });
        program.preassign_label_to_next_insn(next);
    }
    if let Some(else_expr) = else_expr {
        translate_plan_expr_no_constant_opt(
            program,
            referenced_tables,
            else_expr,
            target_register,
            resolver,
            NoConstantOptReason::RegisterReuse,
        )?;
    } else {
        program.emit_insn(Insn::Null {
            dest: target_register,
            dest_end: None,
        });
    }
    program.preassign_label_to_next_insn(done);
    Ok(target_register)
}

fn emit_plan_in_list_value(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    lhs: &PlanExpr,
    values: &[PlanExpr],
    negated: bool,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let width = {
        let facts = resolver.plan_runtime_bindings();
        plan_expr_vector_size(lhs, &*facts)?
    };
    let lhs_register = program.alloc_registers(width);
    translate_plan_expr(program, referenced_tables, lhs, lhs_register, resolver)?;

    let null_seen = program.alloc_register();
    program.emit_insn(Insn::Integer {
        value: 0,
        dest: null_seen,
    });
    program.emit_insn(Insn::Integer {
        value: 0,
        dest: target_register,
    });
    let matched = program.allocate_label();
    let finish = program.allocate_label();

    for value in values {
        let value_width = {
            let facts = resolver.plan_runtime_bindings();
            plan_expr_vector_size(value, &*facts)?
        };
        if value_width != width {
            crate::bail_parse_error!("IN value has {} columns - expected {}", value_width, width);
        }
        let rhs_register = program.alloc_registers(width);
        translate_plan_expr(program, referenced_tables, value, rhs_register, resolver)?;
        let candidate_null = program.alloc_register();
        program.emit_insn(Insn::Integer {
            value: 0,
            dest: candidate_null,
        });
        let next_candidate = program.allocate_label();

        for index in 0..width {
            let mark_null = program.allocate_label();
            let component_done = program.allocate_label();
            program.emit_insn(Insn::IsNull {
                reg: lhs_register + index,
                target_pc: mark_null,
            });
            program.emit_insn(Insn::IsNull {
                reg: rhs_register + index,
                target_pc: mark_null,
            });
            let (affinity, collation) = plan_row_component_comparison(lhs, value, index, resolver)?;
            program.emit_insn(Insn::Ne {
                lhs: lhs_register + index,
                rhs: rhs_register + index,
                target_pc: next_candidate,
                flags: CmpInsFlags::default().with_affinity(affinity),
                collation: Some(collation),
            });
            program.emit_insn(Insn::Goto {
                target_pc: component_done,
            });
            program.preassign_label_to_next_insn(mark_null);
            program.emit_insn(Insn::Integer {
                value: 1,
                dest: candidate_null,
            });
            program.preassign_label_to_next_insn(component_done);
        }

        let candidate_unknown = program.allocate_label();
        program.emit_insn(Insn::If {
            reg: candidate_null,
            target_pc: candidate_unknown,
            jump_if_null: false,
        });
        program.emit_insn(Insn::Goto { target_pc: matched });
        program.preassign_label_to_next_insn(candidate_unknown);
        program.emit_insn(Insn::Integer {
            value: 1,
            dest: null_seen,
        });
        program.preassign_label_to_next_insn(next_candidate);
    }

    let no_null = program.allocate_label();
    program.emit_insn(Insn::IfNot {
        reg: null_seen,
        target_pc: no_null,
        jump_if_null: true,
    });
    program.emit_insn(Insn::Null {
        dest: target_register,
        dest_end: None,
    });
    program.emit_insn(Insn::Goto { target_pc: finish });
    program.preassign_label_to_next_insn(no_null);
    program.emit_insn(Insn::Integer {
        value: i64::from(negated),
        dest: target_register,
    });
    program.emit_insn(Insn::Goto { target_pc: finish });

    program.preassign_label_to_next_insn(matched);
    program.emit_insn(Insn::Integer {
        value: i64::from(!negated),
        dest: target_register,
    });
    program.preassign_label_to_next_insn(finish);
    Ok(target_register)
}

fn emit_plan_subquery(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    subquery: &PlanSubqueryExpr,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let query = match subquery {
        PlanSubqueryExpr::Scalar { query, .. }
        | PlanSubqueryExpr::Exists(query)
        | PlanSubqueryExpr::In { query, .. } => *query,
    };
    let binding = resolver
        .plan_runtime_bindings()
        .subquery(query)
        .cloned()
        .ok_or_else(|| {
            LimboError::InternalError(format!("plan subquery {query} has no runtime binding"))
        })?;

    match (subquery, binding.query_type) {
        (
            PlanSubqueryExpr::Scalar { output, .. },
            PlanSubqueryType::RowValue {
                result_reg_start,
                num_regs,
            },
        ) => {
            if *output >= num_regs {
                return Err(LimboError::InternalError(format!(
                    "scalar subquery {query} output {} exceeds width {num_regs}",
                    output
                )));
            }
            program.emit_insn(Insn::Copy {
                src_reg: result_reg_start + output,
                dst_reg: target_register,
                extra_amount: 0,
            });
            Ok(target_register)
        }
        (PlanSubqueryExpr::Exists(_), PlanSubqueryType::Exists { result_reg }) => {
            program.emit_insn(Insn::Copy {
                src_reg: result_reg,
                dst_reg: target_register,
                extra_amount: 0,
            });
            Ok(target_register)
        }
        (
            PlanSubqueryExpr::In { lhs, negated, .. },
            PlanSubqueryType::In {
                cursor_id,
                affinity_str,
            },
        ) => emit_plan_in_subquery_value(
            program,
            referenced_tables,
            lhs,
            *negated,
            cursor_id,
            &affinity_str,
            target_register,
            resolver,
        ),
        _ => Err(LimboError::InternalError(format!(
            "plan subquery {query} runtime shape does not match its semantic use"
        ))),
    }
}

#[allow(clippy::too_many_arguments)]
fn emit_plan_in_subquery_value(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    lhs: &PlanExpr,
    negated: bool,
    cursor_id: usize,
    affinity_str: &str,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let width = {
        let facts = resolver.plan_runtime_bindings();
        plan_expr_vector_size(lhs, &*facts)?
    };
    if affinity_str.chars().count() != width {
        return Err(LimboError::InternalError(format!(
            "IN subquery affinity width {} does not match left row width {width}",
            affinity_str.chars().count()
        )));
    }

    let false_result = program.allocate_label();
    let true_result = program.allocate_label();
    let null_result = program.allocate_label();
    let inspect_nulls = program.allocate_label();
    let null_loop = program.allocate_label();
    let next_null_row = program.allocate_label();
    let done = program.allocate_label();
    let lhs_register = program.alloc_registers(width);
    translate_plan_expr(program, referenced_tables, lhs, lhs_register, resolver)?;
    for index in 0..width {
        program.emit_insn(Insn::IsNull {
            reg: lhs_register + index,
            target_pc: inspect_nulls,
        });
    }

    if affinity_str
        .chars()
        .map(Affinity::from_char)
        .any(|affinity| affinity != Affinity::Blob)
    {
        if let Ok(count) = std::num::NonZeroUsize::try_from(width) {
            program.emit_insn(Insn::Affinity {
                start_reg: lhs_register,
                count,
                affinities: affinity_str.to_string(),
            });
        }
    }

    let no_null_result = if negated { true_result } else { false_result };
    if negated {
        program.emit_insn(Insn::Found {
            cursor_id,
            target_pc: false_result,
            record_reg: lhs_register,
            num_regs: width,
        });
    } else {
        program.emit_insn(Insn::NotFound {
            cursor_id,
            target_pc: inspect_nulls,
            record_reg: lhs_register,
            num_regs: width,
        });
        program.emit_insn(Insn::Goto {
            target_pc: true_result,
        });
    }

    program.preassign_label_to_next_insn(inspect_nulls);
    program.emit_insn(Insn::Rewind {
        cursor_id,
        pc_if_empty: no_null_result,
    });
    program.preassign_label_to_next_insn(null_loop);
    let rhs_register = program.alloc_register();
    for (index, affinity) in affinity_str.chars().map(Affinity::from_char).enumerate() {
        program.emit_insn(Insn::Column {
            cursor_id,
            column: index,
            dest: rhs_register,
            default: None,
        });
        program.emit_insn(Insn::Ne {
            lhs: lhs_register + index,
            rhs: rhs_register,
            target_pc: next_null_row,
            flags: CmpInsFlags::default().with_affinity(affinity),
            collation: program.curr_collation(),
        });
    }
    program.emit_insn(Insn::Goto {
        target_pc: null_result,
    });
    program.preassign_label_to_next_insn(next_null_row);
    program.emit_insn(Insn::Next {
        cursor_id,
        pc_if_next: null_loop,
    });
    program.emit_insn(Insn::Goto {
        target_pc: no_null_result,
    });

    program.preassign_label_to_next_insn(true_result);
    program.emit_insn(Insn::Integer {
        value: 1,
        dest: target_register,
    });
    program.emit_insn(Insn::Goto { target_pc: done });
    program.preassign_label_to_next_insn(false_result);
    program.emit_insn(Insn::Integer {
        value: 0,
        dest: target_register,
    });
    program.emit_insn(Insn::Goto { target_pc: done });
    program.preassign_label_to_next_insn(null_result);
    program.emit_insn(Insn::Null {
        dest: target_register,
        dest_end: None,
    });
    program.preassign_label_to_next_insn(done);
    Ok(target_register)
}

#[allow(clippy::too_many_arguments)]
fn emit_plan_like(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    lhs: &PlanExpr,
    negated: bool,
    operator: LikeOperator,
    function: &crate::translate::semantic::hir::ResolvedFunction,
    argument_count: usize,
    rhs: &PlanExpr,
    escape: Option<&PlanExpr>,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let result = if negated {
        program.alloc_register()
    } else {
        target_register
    };
    let arguments = program.alloc_registers(argument_count.max(1));
    match operator {
        LikeOperator::Match => {
            let mut offset = 0;
            if let PlanExpr::Row(columns) = lhs {
                for column in columns {
                    translate_plan_expr(
                        program,
                        referenced_tables,
                        column,
                        arguments + offset,
                        resolver,
                    )?;
                    offset += 1;
                }
            } else {
                translate_plan_expr(program, referenced_tables, lhs, arguments, resolver)?;
                offset = 1;
            }
            translate_plan_expr(
                program,
                referenced_tables,
                rhs,
                arguments + offset,
                resolver,
            )?;
            if offset + 1 != argument_count {
                return Err(LimboError::InternalError(
                    "MATCH argument count changed after semantic analysis".to_string(),
                ));
            }
        }
        LikeOperator::Like | LikeOperator::Glob | LikeOperator::Regexp => {
            translate_plan_expr(program, referenced_tables, rhs, arguments, resolver)?;
            translate_plan_expr(program, referenced_tables, lhs, arguments + 1, resolver)?;
            if let Some(escape) = escape {
                translate_plan_expr(program, referenced_tables, escape, arguments + 2, resolver)?;
            }
            if 2 + usize::from(escape.is_some()) != argument_count {
                return Err(LimboError::InternalError(
                    "LIKE argument count changed after semantic analysis".to_string(),
                ));
            }
        }
    }
    let constant_mask = i32::from(matches!(rhs, PlanExpr::Literal(_)));
    program.emit_insn(Insn::Function {
        constant_mask,
        start_reg: arguments,
        dest: result,
        func: FuncCtx {
            func: function.value().clone(),
            arg_count: argument_count,
        },
    });
    if negated {
        program.emit_insn(Insn::Not {
            reg: result,
            dest: target_register,
        });
    }
    Ok(target_register)
}

fn emit_plan_function(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    function: &PlanFunctionCall,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    if let Some(operation) = &function.custom_type_operation {
        return emit_plan_custom_type_function(
            program,
            referenced_tables,
            function,
            operation,
            target_register,
            resolver,
        );
    }
    if let Some(operation) = &function.sequence_operation {
        return emit_plan_sequence_function(
            program,
            referenced_tables,
            function,
            operation,
            target_register,
            resolver,
        );
    }

    let resolved = function.function.value().clone();
    match &resolved {
        Func::Agg(aggregate) => {
            return Err(LimboError::InternalError(format!(
                "aggregate function {aggregate} reached scalar PlanExpr emission"
            )));
        }
        Func::Window(window) => {
            return Err(LimboError::InternalError(format!(
                "window function {window} reached scalar PlanExpr emission"
            )));
        }
        Func::Scalar(ScalarFunc::Cast) => {
            return Err(LimboError::InternalError(
                "CAST function reached PlanExpr emission instead of PlanExpr::Cast".to_string(),
            ));
        }
        Func::Scalar(ScalarFunc::Array | ScalarFunc::StructPack) => {
            return emit_plan_array(
                program,
                referenced_tables,
                &function.arguments,
                target_register,
                resolver,
            );
        }
        Func::Scalar(ScalarFunc::ArrayElement) => {
            let [array, index] = function.arguments.as_slice() else {
                return Err(LimboError::InternalError(
                    "array_element has invalid resolved arity".to_string(),
                ));
            };
            let arguments = program.alloc_registers(2);
            translate_plan_expr(program, referenced_tables, array, arguments, resolver)?;
            translate_plan_expr(program, referenced_tables, index, arguments + 1, resolver)?;
            program.emit_insn(Insn::ArrayElement {
                array_reg: arguments,
                index_reg: arguments + 1,
                dest: target_register,
            });
            return Ok(target_register);
        }
        Func::Scalar(ScalarFunc::ArraySetElement) => {
            let [array, index, value] = function.arguments.as_slice() else {
                return Err(LimboError::InternalError(
                    "array_set_element has invalid resolved arity".to_string(),
                ));
            };
            let arguments = program.alloc_registers(3);
            translate_plan_expr(program, referenced_tables, array, arguments, resolver)?;
            translate_plan_expr(program, referenced_tables, index, arguments + 1, resolver)?;
            translate_plan_expr(program, referenced_tables, value, arguments + 2, resolver)?;
            program.emit_insn(Insn::ArraySetElement {
                array_reg: arguments,
                index_reg: arguments + 1,
                value_reg: arguments + 2,
                dest: target_register,
            });
            return Ok(target_register);
        }
        Func::Scalar(ScalarFunc::Coalesce | ScalarFunc::IfNull) => {
            if function.arguments.len() < 2 {
                return Err(LimboError::InternalError(format!(
                    "{} has invalid resolved arity",
                    resolved
                )));
            }
            let done = program.allocate_label();
            for (index, argument) in function.arguments.iter().enumerate() {
                translate_plan_expr_no_constant_opt(
                    program,
                    referenced_tables,
                    argument,
                    target_register,
                    resolver,
                    NoConstantOptReason::RegisterReuse,
                )?;
                if index + 1 != function.arguments.len() {
                    program.emit_insn(Insn::NotNull {
                        reg: target_register,
                        target_pc: done,
                    });
                }
            }
            program.preassign_label_to_next_insn(done);
            return Ok(target_register);
        }
        Func::Scalar(ScalarFunc::Iif) => {
            if function.arguments.len() < 2 {
                return Err(LimboError::InternalError(
                    "iif has invalid resolved arity".to_string(),
                ));
            }
            let done = program.allocate_label();
            let condition = program.alloc_register();
            for pair in function.arguments.chunks_exact(2) {
                let next = program.allocate_label();
                translate_plan_expr_no_constant_opt(
                    program,
                    referenced_tables,
                    &pair[0],
                    condition,
                    resolver,
                    NoConstantOptReason::RegisterReuse,
                )?;
                program.emit_insn(Insn::IfNot {
                    reg: condition,
                    target_pc: next,
                    jump_if_null: true,
                });
                translate_plan_expr_no_constant_opt(
                    program,
                    referenced_tables,
                    &pair[1],
                    target_register,
                    resolver,
                    NoConstantOptReason::RegisterReuse,
                )?;
                program.emit_insn(Insn::Goto { target_pc: done });
                program.preassign_label_to_next_insn(next);
            }
            if function.arguments.len() % 2 == 1 {
                translate_plan_expr_no_constant_opt(
                    program,
                    referenced_tables,
                    function.arguments.last().expect("odd argument exists"),
                    target_register,
                    resolver,
                    NoConstantOptReason::RegisterReuse,
                )?;
            } else {
                program.emit_insn(Insn::Null {
                    dest: target_register,
                    dest_end: None,
                });
            }
            program.preassign_label_to_next_insn(done);
            return Ok(target_register);
        }
        Func::Scalar(ScalarFunc::Likely | ScalarFunc::Unlikely | ScalarFunc::Likelihood) => {
            let argument = function.arguments.first().ok_or_else(|| {
                LimboError::InternalError(format!("{} has invalid resolved arity", resolved))
            })?;
            return translate_plan_expr(
                program,
                referenced_tables,
                argument,
                target_register,
                resolver,
            );
        }
        Func::Scalar(ScalarFunc::NextVal | ScalarFunc::SetVal) => {
            return Err(LimboError::InternalError(format!(
                "{} is missing resolved sequence metadata",
                resolved
            )));
        }
        Func::Scalar(ScalarFunc::Attach | ScalarFunc::Detach) => {
            crate::bail_parse_error!("{} is only valid as a statement", resolved);
        }
        Func::Scalar(ScalarFunc::StatInit | ScalarFunc::StatPush | ScalarFunc::StatGet) => {
            crate::bail_parse_error!("{} is an internal function used by ANALYZE", resolved);
        }
        _ => {}
    }

    let arguments = program.alloc_registers(function.arguments.len().max(1));
    for (offset, argument) in function.arguments.iter().enumerate() {
        translate_plan_expr(
            program,
            referenced_tables,
            argument,
            arguments + offset,
            resolver,
        )?;
    }
    program.emit_insn(Insn::Function {
        constant_mask: 0,
        start_reg: arguments,
        dest: target_register,
        func: FuncCtx {
            func: resolved,
            arg_count: function.arguments.len(),
        },
    });
    Ok(target_register)
}

fn emit_plan_custom_type_function(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    function: &PlanFunctionCall,
    operation: &PlanCustomTypeOperation,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    match operation {
        PlanCustomTypeOperation::UnionValue { tag_index, .. } => {
            let [_tag, value] = function.arguments.as_slice() else {
                return Err(LimboError::InternalError(
                    "resolved union_value has invalid arity".to_string(),
                ));
            };
            let source = program.alloc_register();
            translate_plan_expr(program, referenced_tables, value, source, resolver)?;
            program.emit_insn(Insn::UnionPack {
                tag_index: *tag_index,
                value_reg: source,
                dest: target_register,
            });
        }
        PlanCustomTypeOperation::UnionTag { tag_names, .. } => {
            let [source] = function.arguments.as_slice() else {
                return Err(LimboError::InternalError(
                    "resolved union_tag has invalid arity".to_string(),
                ));
            };
            let source_register = program.alloc_register();
            translate_plan_expr(
                program,
                referenced_tables,
                source,
                source_register,
                resolver,
            )?;
            program.emit_insn(Insn::UnionTag {
                src_reg: source_register,
                dest: target_register,
                tag_names: tag_names.clone(),
            });
        }
        PlanCustomTypeOperation::UnionExtract { tag_index, .. } => {
            let [source, _tag] = function.arguments.as_slice() else {
                return Err(LimboError::InternalError(
                    "resolved union_extract has invalid arity".to_string(),
                ));
            };
            let source_register = program.alloc_register();
            translate_plan_expr(
                program,
                referenced_tables,
                source,
                source_register,
                resolver,
            )?;
            program.emit_insn(Insn::UnionExtract {
                src_reg: source_register,
                expected_tag: *tag_index,
                dest: target_register,
            });
        }
        PlanCustomTypeOperation::StructExtract { field_index, .. } => {
            let [source, _field] = function.arguments.as_slice() else {
                return Err(LimboError::InternalError(
                    "resolved struct_extract has invalid arity".to_string(),
                ));
            };
            let source_register = program.alloc_register();
            translate_plan_expr(
                program,
                referenced_tables,
                source,
                source_register,
                resolver,
            )?;
            program.emit_insn(Insn::StructField {
                src_reg: source_register,
                field_index: *field_index,
                dest: target_register,
            });
        }
    }
    Ok(target_register)
}

fn emit_plan_sequence_function(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    function: &PlanFunctionCall,
    operation: &PlanSequenceOperation,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<usize> {
    let arguments = program.alloc_registers(function.arguments.len().max(1));
    for (offset, argument) in function.arguments.iter().enumerate() {
        translate_plan_expr(
            program,
            referenced_tables,
            argument,
            arguments + offset,
            resolver,
        )?;
    }
    let database = operation.database.index();
    program.begin_write_on_database(database, operation.schema_cookie)?;

    match operation.kind {
        PlanSequenceOperationKind::NextValue => {
            crate::translate::sequence::emit_disk_read_nextval(
                program,
                resolver,
                database,
                &operation.normalized_name,
                &operation.sequence,
                target_register,
                Some(arguments),
            )?;
        }
        PlanSequenceOperationKind::SetValue => {
            let Table::BTree(backing_table) = operation.backing_table.value() else {
                return Err(LimboError::InternalError(format!(
                    "resolved backing object for sequence {} is not a B-tree table",
                    operation.user_name
                )));
            };
            let cursor = program.alloc_cursor_id(CursorType::BTreeTable(backing_table.clone()));
            program.emit_insn(Insn::OpenWrite {
                cursor_id: cursor,
                root_page: RegisterOrLiteral::Literal(backing_table.root_page),
                db: database,
            });
            program.emit_insn(Insn::Function {
                constant_mask: 0,
                start_reg: arguments,
                dest: target_register,
                func: FuncCtx {
                    func: function.function.value().clone(),
                    arg_count: function.arguments.len(),
                },
            });

            let empty = program.allocate_label();
            let delete_loop = program.allocate_label();
            program.emit_insn(Insn::Rewind {
                cursor_id: cursor,
                pc_if_empty: empty,
            });
            program.preassign_label_to_next_insn(delete_loop);
            program.emit_insn(Insn::Delete {
                cursor_id: cursor,
                table_name: operation.normalized_name.clone(),
                is_part_of_update: true,
            });
            program.emit_insn(Insn::Next {
                cursor_id: cursor,
                pc_if_next: delete_loop,
            });
            program.preassign_label_to_next_insn(empty);

            let columns = program.alloc_registers(7);
            program.emit_insn(Insn::Copy {
                src_reg: arguments + 1,
                dst_reg: columns,
                extra_amount: 0,
            });
            if function.arguments.len() > 2 {
                program.emit_insn(Insn::Copy {
                    src_reg: arguments + 2,
                    dst_reg: columns + 1,
                    extra_amount: 0,
                });
            } else {
                program.emit_insn(Insn::Integer {
                    value: 1,
                    dest: columns + 1,
                });
            }
            crate::translate::sequence::emit_sequence_descriptor_literals(
                program,
                &operation.sequence,
                columns + 2,
            );
            let record = program.alloc_register();
            program.emit_insn(Insn::MakeRecord {
                start_reg: to_u32(columns),
                count: 7,
                dest_reg: to_u32(record),
                index_name: None,
                affinity_str: None,
            });
            program.emit_insn(Insn::Insert {
                cursor,
                key_reg: arguments + 1,
                record_reg: record,
                flag: InsertFlags::new().require_seek().skip_all_change_counts(),
                table_name: operation.normalized_name.clone(),
            });
            program.emit_insn(Insn::SetSequenceCurrval {
                seq_name_reg: arguments,
                value_reg: arguments + 1,
            });
            program.emit_insn(Insn::Close { cursor_id: cursor });
            crate::translate::sequence::emit_autoincrement_sqlite_sequence_sync(
                program,
                resolver,
                database,
                &operation.normalized_name,
                arguments + 1,
            )?;
        }
    }
    Ok(target_register)
}

fn emit_plan_cast(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    target: &PlanTypeName,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    if !target.programs.apply_builtin_affinity {
        emit_plan_cast_programs(
            program,
            referenced_tables,
            &target.programs,
            target_register,
            resolver,
        )?;
        return Ok(());
    }

    program.emit_insn(Insn::Cast {
        reg: target_register,
        affinity: target.cast_affinity(),
    });
    Ok(())
}

/// Emit one frozen schema-program call for a runtime value.
#[allow(clippy::too_many_arguments)]
pub(crate) fn emit_plan_schema_call(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    call: &PlanBoundSchemaCall,
    value_register: usize,
    destination_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    let mut columns = Vec::with_capacity(call.arguments.len() + 1);
    columns.push(RuntimeValueBinding::Register {
        register: value_register,
        needs_decode: false,
    });
    for argument in &call.arguments {
        let register = program.alloc_register();
        translate_plan_expr(program, referenced_tables, argument, register, resolver)?;
        columns.push(RuntimeValueBinding::Register {
            register,
            needs_decode: false,
        });
    }

    let mut bindings = PlanRuntimeBindings::default();
    bindings.bind_row(
        call.program.input_source,
        RuntimeRowBinding {
            columns,
            rowid: None,
            read_programs: None,
        },
    );
    resolver.with_plan_runtime_bindings(bindings, |resolver| {
        translate_plan_expr_no_constant_opt(
            program,
            None,
            &call.program.body,
            destination_register,
            resolver,
            NoConstantOptReason::RegisterReuse,
        )?;
        Ok(())
    })
}

fn emit_plan_cast_programs(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    programs: &PlanCastPrograms,
    value_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    for encoder in &programs.encode {
        emit_plan_schema_call(
            program,
            referenced_tables,
            encoder,
            value_register,
            value_register,
            resolver,
        )?;
    }
    if let Some(domain) = &programs.domain {
        emit_plan_domain_constraints(program, referenced_tables, domain, value_register, resolver)?;
    }
    Ok(())
}

fn emit_plan_domain_constraints(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    constraints: &PlanDomainConstraints,
    value_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    use crate::error::{SQLITE_CONSTRAINT_CHECK, SQLITE_CONSTRAINT_NOTNULL};

    if let Some(description) = &constraints.not_null_description {
        program.emit_insn(Insn::HaltIfNull {
            target_reg: value_register,
            err_code: SQLITE_CONSTRAINT_NOTNULL,
            description: description.clone(),
        });
    }

    for check in &constraints.checks {
        let result = program.alloc_register();
        emit_plan_schema_call(
            program,
            referenced_tables,
            &check.call,
            value_register,
            result,
            resolver,
        )?;
        let passed = program.allocate_label();
        program.emit_insn(Insn::IsNull {
            reg: result,
            target_pc: passed,
        });
        program.emit_insn(Insn::If {
            reg: result,
            target_pc: passed,
            jump_if_null: false,
        });
        program.emit_insn(Insn::Halt {
            err_code: SQLITE_CONSTRAINT_CHECK,
            description: check.failure_description.clone(),
            on_error: None,
            description_reg: None,
        });
        program.preassign_label_to_next_insn(passed);
    }
    Ok(())
}

fn emit_plan_value_decode(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    expr: &PlanExpr,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    match expr {
        PlanExpr::Column(column) => emit_plan_column_decode(
            program,
            referenced_tables,
            column,
            target_register,
            resolver,
        ),
        PlanExpr::MergedColumn(column) => match column.value {
            PlanMergedColumnValue::Right => emit_plan_column_decode(
                program,
                referenced_tables,
                &column.right,
                target_register,
                resolver,
            ),
            PlanMergedColumnValue::Left | PlanMergedColumnValue::Coalesce => Ok(()),
        },
        _ => Ok(()),
    }
}

fn emit_plan_column_decode(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    column: &PlanColumnRef,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    let Some(programs) = plan_column_type_programs(referenced_tables, column, resolver)? else {
        return Ok(());
    };
    emit_plan_column_value_decode(
        program,
        referenced_tables,
        &programs,
        target_register,
        resolver,
    )
}

/// Decode one stored scalar value with an explicit source codec bundle.
/// Array values stay in record form until the result-row boundary.
pub(crate) fn emit_plan_column_value_decode(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    programs: &PlanColumnTypePrograms,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    // Arrays remain in their native record representation while expressions
    // run. The result-row boundary converts them to user-facing text.
    if programs.array.is_some() || programs.decode.is_empty() {
        return Ok(());
    }
    let done = program.allocate_label();
    program.emit_insn(Insn::IsNull {
        reg: target_register,
        target_pc: done,
    });
    for decoder in &programs.decode {
        emit_plan_schema_call(
            program,
            referenced_tables,
            decoder,
            target_register,
            target_register,
            resolver,
        )?;
    }
    program.preassign_label_to_next_insn(done);
    Ok(())
}

/// Decode a stored value before a whole-row encode pass. Arrays decode their
/// elements but remain in record form so the later encoder can consume them.
pub(crate) fn emit_plan_column_value_decode_for_reencode(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    programs: &PlanColumnTypePrograms,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    if programs.array.is_none() {
        return emit_plan_column_value_decode(
            program,
            referenced_tables,
            programs,
            target_register,
            resolver,
        );
    }
    if programs.decode.is_empty() {
        return Ok(());
    }

    let done = program.allocate_label();
    program.emit_insn(Insn::IsNull {
        reg: target_register,
        target_pc: done,
    });
    emit_plan_array_element_transforms(
        program,
        referenced_tables,
        target_register,
        &programs.decode,
        resolver,
    )?;
    program.preassign_label_to_next_insn(done);
    Ok(())
}

/// Encode one value for storage with an explicit source codec bundle.
pub(crate) fn emit_plan_column_value_encode(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    programs: &PlanColumnTypePrograms,
    target_register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    if programs.array.is_none() && programs.encode.is_empty() {
        return Ok(());
    }
    let skip_null = programs.array.is_some() || !programs.encode_nulls;
    let done = skip_null.then(|| {
        let done = program.allocate_label();
        program.emit_insn(Insn::IsNull {
            reg: target_register,
            target_pc: done,
        });
        done
    });
    if let Some(array) = &programs.array {
        emit_plan_array_encode(
            program,
            referenced_tables,
            target_register,
            array,
            &programs.encode,
            resolver,
        )?;
    } else {
        for encoder in &programs.encode {
            emit_plan_schema_call(
                program,
                referenced_tables,
                encoder,
                target_register,
                target_register,
                resolver,
            )?;
        }
    }
    if let Some(done) = done {
        program.preassign_label_to_next_insn(done);
    }
    Ok(())
}

fn plan_column_type_programs(
    referenced_tables: Option<&TableReferences>,
    column: &PlanColumnRef,
    resolver: &Resolver<'_>,
) -> Result<Option<PlanColumnTypePrograms>> {
    let read_programs = referenced_tables
        .and_then(|tables| tables.find_source_read_programs_by_internal_id(column.source));
    if let Some(read_programs) = read_programs {
        return read_programs
            .column_type_programs
            .get(column.column)
            .ok_or_else(|| {
                LimboError::InternalError(format!(
                    "source read programs for {} omit column {}",
                    column.source, column.column
                ))
            })
            .cloned();
    }

    let read_programs = resolver
        .plan_runtime_bindings()
        .read_programs(column.source)
        .ok_or_else(|| {
            LimboError::InternalError(format!(
                "plan column {}.{} has no source read programs",
                column.source, column.column
            ))
        })?;
    read_programs
        .column_type_programs
        .get(column.column)
        .ok_or_else(|| {
            LimboError::InternalError(format!(
                "source read programs for {} omit column {}",
                column.source, column.column
            ))
        })
        .cloned()
}

fn emit_plan_array_encode(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    register: usize,
    array: &PlanArrayStorage,
    element_encoders: &[PlanBoundSchemaCall],
    resolver: &Resolver<'_>,
) -> Result<()> {
    if array.dimensions == 0 {
        return Err(LimboError::InternalError(
            "array storage program has zero dimensions".to_string(),
        ));
    }
    if !element_encoders.is_empty() {
        program.emit_insn(Insn::ArrayEncode {
            reg: register,
            element_affinity: Affinity::Blob,
            element_type: "ANY".into(),
            table_name: array.table_name.clone().into(),
            col_name: array.column_name.clone().into(),
        });
        emit_plan_array_element_transforms(
            program,
            referenced_tables,
            register,
            element_encoders,
            resolver,
        )?;
    }

    program.emit_insn(Insn::ArrayEncode {
        reg: register,
        element_affinity: array.element_affinity,
        element_type: array.element_type.clone().into(),
        table_name: array.table_name.clone().into(),
        col_name: array.column_name.clone().into(),
    });
    Ok(())
}

fn emit_plan_array_element_transforms(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    array_register: usize,
    transforms: &[PlanBoundSchemaCall],
    resolver: &Resolver<'_>,
) -> Result<()> {
    const MAX_ELEMENTS: usize = 1024;

    let length = program.alloc_register();
    let index = program.alloc_register();
    let element = program.alloc_register();
    let elements = program.alloc_registers(MAX_ELEMENTS);
    let offset = program.alloc_register();
    program.emit_insn(Insn::ArrayLength {
        reg: array_register,
        dest: length,
    });
    let maximum = program.alloc_register();
    program.emit_insn(Insn::Integer {
        value: MAX_ELEMENTS as i64,
        dest: maximum,
    });
    let size_ok = program.allocate_label();
    program.emit_insn(Insn::Le {
        lhs: length,
        rhs: maximum,
        target_pc: size_ok,
        flags: CmpInsFlags::default(),
        collation: None,
    });
    program.emit_insn(Insn::Halt {
        err_code: crate::error::SQLITE_CONSTRAINT,
        description: format!(
            "array exceeds maximum element count for custom type transform ({MAX_ELEMENTS})"
        ),
        on_error: None,
        description_reg: None,
    });
    program.preassign_label_to_next_insn(size_ok);
    program.emit_insn(Insn::Integer {
        value: 1,
        dest: index,
    });
    program.emit_insn(Insn::Integer {
        value: 0,
        dest: offset,
    });
    let loop_start = program.offset();
    let loop_done = program.allocate_label();
    program.emit_insn(Insn::Gt {
        lhs: index,
        rhs: length,
        target_pc: loop_done,
        flags: CmpInsFlags::default(),
        collation: None,
    });
    program.emit_insn(Insn::ArrayElement {
        array_reg: array_register,
        index_reg: index,
        dest: element,
    });
    for transform in transforms {
        emit_plan_schema_call(
            program,
            referenced_tables,
            transform,
            element,
            element,
            resolver,
        )?;
    }
    program.emit_insn(Insn::RegCopyOffset {
        src: element,
        base: elements,
        offset_reg: offset,
    });
    program.emit_insn(Insn::AddImm {
        register: index,
        value: 1,
    });
    program.emit_insn(Insn::AddImm {
        register: offset,
        value: 1,
    });
    program.emit_insn(Insn::Goto {
        target_pc: loop_start,
    });
    program.preassign_label_to_next_insn(loop_done);
    program.emit_insn(Insn::MakeArrayDynamic {
        start_reg: elements,
        count_reg: length,
        dest: array_register,
    });
    Ok(())
}

/// Convert a resolved array result from its internal record representation to
/// user-facing JSON. A direct custom-type column uses its frozen source read
/// programs to decode each element before the final array conversion; all
/// other array-producing expressions only need the record-to-JSON step.
pub(crate) fn emit_plan_result_array_decode(
    program: &mut ProgramBuilder,
    referenced_tables: &TableReferences,
    expr: &PlanExpr,
    type_fact: &crate::translate::semantic::hir::TypeFact,
    register: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    // A compound or CASE result can keep a direct-column expression while
    // its merged type no longer guarantees that every row uses that column's
    // custom array encoding.
    let column = type_fact.declared.as_ref().and_then(|_| match expr {
        PlanExpr::Column(column) => Some(column),
        PlanExpr::MergedColumn(column) => match column.value {
            PlanMergedColumnValue::Right => Some(&column.right),
            PlanMergedColumnValue::Left | PlanMergedColumnValue::Coalesce => None,
        },
        _ => None,
    });

    if let Some(column) = column {
        if let Some(programs) =
            plan_column_type_programs(Some(referenced_tables), column, resolver)?
        {
            if programs.array.is_some() && !programs.decode.is_empty() {
                emit_plan_array_element_transforms(
                    program,
                    Some(referenced_tables),
                    register,
                    &programs.decode,
                    resolver,
                )?;
            }
        }
    }

    program.emit_insn(Insn::ArrayDecode {
        reg: register,
        dimensions: type_fact.array_dimensions,
        rank_unbounded: type_fact.array_rank_unbounded,
    });
    Ok(())
}

/// Compile one stored custom-type ENCODE or DECODE expression through semantic
/// analysis for a legacy schema-only caller.
pub(crate) fn emit_schema_type_transform(
    program: &mut ProgramBuilder,
    expression: Option<&SchemaExpr>,
    value_register: usize,
    destination_register: usize,
    column: &Column,
    definition: &crate::schema::TypeDef,
    resolver: &Resolver<'_>,
) -> Result<()> {
    emit_schema_type_transform_in_database(
        program,
        expression,
        value_register,
        destination_register,
        column,
        definition,
        crate::MAIN_DB_ID,
        resolver,
    )
}

#[allow(clippy::too_many_arguments)]
fn emit_schema_type_transform_in_database(
    program: &mut ProgramBuilder,
    expression: Option<&SchemaExpr>,
    value_register: usize,
    destination_register: usize,
    column: &Column,
    definition: &crate::schema::TypeDef,
    database: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    let Some(expression) = expression else {
        if value_register != destination_register {
            program.emit_insn(Insn::Copy {
                src_reg: value_register,
                dst_reg: destination_register,
                extra_amount: 0,
            });
        }
        return Ok(());
    };
    let parameters = column
        .ty_params
        .iter()
        .map(|parameter| {
            lower_standalone_schema_expr(program, resolver, database, parameter.as_valid()?)
        })
        .collect::<Result<Vec<_>>>()?;
    emit_schema_type_transform_with_parameters(
        program,
        None,
        Some(expression),
        value_register,
        destination_register,
        &parameters,
        definition,
        database,
        resolver,
    )
}

#[allow(clippy::too_many_arguments)]
fn emit_schema_type_transform_with_parameters(
    program: &mut ProgramBuilder,
    referenced_tables: Option<&TableReferences>,
    expression: Option<&SchemaExpr>,
    value_register: usize,
    destination_register: usize,
    parameters: &[PlanExpr],
    definition: &crate::schema::TypeDef,
    database: usize,
    resolver: &Resolver<'_>,
) -> Result<()> {
    let Some(expression) = expression else {
        if value_register != destination_register {
            program.emit_insn(Insn::Copy {
                src_reg: value_register,
                dst_reg: destination_register,
                extra_amount: 0,
            });
        }
        return Ok(());
    };
    let expression = expression.as_valid()?;
    let user_parameters = definition.user_params().collect::<Vec<_>>();
    if parameters.len() != user_parameters.len() {
        return Err(LimboError::InternalError(format!(
            "custom type {} expects {} parameters but its application has {}",
            definition.name,
            user_parameters.len(),
            parameters.len()
        )));
    }
    let facts = resolver.plan_runtime_bindings();
    let mut inputs = Vec::with_capacity(parameters.len() + 1);
    inputs.push(SchemaExprInput {
        name: "value".to_string(),
        declared_type: Some(definition.value_input_type().to_string()),
        array_dimensions: 0,
        type_fact: None,
    });
    for (parameter, value) in user_parameters.iter().zip(parameters) {
        inputs.push(SchemaExprInput {
            name: parameter.name.clone(),
            declared_type: parameter.ty.clone(),
            array_dimensions: 0,
            type_fact: Some(plan_expr_type_fact(value, &*facts)),
        });
    }
    drop(facts);
    let context = resolver.semantic_context();
    let analyzed = analyze_type_transform_schema_expr(&context, database, expression, &inputs)?;
    let (source, expression) = lower_analyzed_schema_expr(program, analyzed)?;
    let mut columns = Vec::with_capacity(parameters.len() + 1);
    columns.push(RuntimeValueBinding::Register {
        register: value_register,
        needs_decode: false,
    });
    for parameter in parameters {
        let register = program.alloc_register();
        translate_plan_expr(program, referenced_tables, parameter, register, resolver)?;
        columns.push(RuntimeValueBinding::Register {
            register,
            needs_decode: false,
        });
    }
    let mut bindings = PlanRuntimeBindings::default();
    bindings.bind_row(
        source,
        RuntimeRowBinding {
            columns,
            rowid: None,
            read_programs: None,
        },
    );
    resolver.with_plan_runtime_bindings(bindings, |resolver| {
        translate_plan_expr_no_constant_opt(
            program,
            None,
            &expression,
            destination_register,
            resolver,
            NoConstantOptReason::RegisterReuse,
        )?;
        Ok(())
    })
}

fn lower_standalone_schema_expr(
    program: &mut ProgramBuilder,
    resolver: &Resolver<'_>,
    database: usize,
    expression: &ValidSchemaExpr,
) -> Result<PlanExpr> {
    let context = resolver.semantic_context();
    let analyzed = analyze_standalone_schema_expr(&context, database, expression)?;
    let (_, expression) = lower_analyzed_schema_expr(program, analyzed)?;
    Ok(expression)
}

fn lower_analyzed_schema_expr(
    program: &mut ProgramBuilder,
    analyzed: AnalyzedSchemaExpr,
) -> Result<(crate::translate::plan_expr::PlanSourceId, PlanExpr)> {
    let source = program.next_plan_source_id();
    let mut identities = PlanIdentityMap::new();
    identities.bind_source_definition(&analyzed.source, source);
    let expression = lower_hir_expr(&analyzed.expression, &identities).map_err(|error| {
        LimboError::InternalError(format!("failed to lower stored expression: {error}"))
    })?;
    Ok((source, expression))
}

/// Compile stored domain constraints through semantic analysis for a legacy
/// schema-only caller.
pub(crate) fn emit_schema_domain_constraints(
    program: &mut ProgramBuilder,
    value_register: usize,
    chain: &[crate::sync::Arc<crate::schema::TypeDef>],
    resolver: &Resolver<'_>,
) -> Result<()> {
    let definitions = chain
        .iter()
        .map(|definition| (crate::MAIN_DB_ID, definition.as_ref()))
        .collect::<Vec<_>>();
    emit_schema_domain_constraints_impl(program, value_register, None, &definitions, resolver)
}

fn emit_schema_domain_constraints_impl(
    program: &mut ProgramBuilder,
    value_register: usize,
    value_type: Option<&crate::translate::semantic::hir::TypeFact>,
    chain: &[(usize, &crate::schema::TypeDef)],
    resolver: &Resolver<'_>,
) -> Result<()> {
    use crate::error::{SQLITE_CONSTRAINT_CHECK, SQLITE_CONSTRAINT_NOTNULL};

    if chain.iter().any(|(_, definition)| definition.not_null) {
        program.emit_insn(Insn::HaltIfNull {
            target_reg: value_register,
            err_code: SQLITE_CONSTRAINT_NOTNULL,
            description: format!(
                "domain {} does not allow null values",
                chain
                    .first()
                    .map(|(_, definition)| definition.name.as_str())
                    .unwrap_or("?")
            ),
        });
    }

    for (database, definition) in chain {
        for (index, constraint) in definition.domain_checks.iter().enumerate() {
            let expression = constraint.check.as_valid()?;
            let context = resolver.semantic_context();
            let analyzed = analyze_domain_check_schema_expr(
                &context,
                *database,
                expression,
                SchemaExprInput {
                    name: "value".to_string(),
                    declared_type: Some(definition.name.clone()),
                    array_dimensions: 0,
                    type_fact: value_type.cloned(),
                },
            )?;
            let (source, expression) = lower_analyzed_schema_expr(program, analyzed)?;
            let mut bindings = PlanRuntimeBindings::default();
            bindings.bind_row(
                source,
                RuntimeRowBinding {
                    columns: vec![RuntimeValueBinding::Register {
                        register: value_register,
                        needs_decode: false,
                    }],
                    rowid: None,
                    read_programs: None,
                },
            );
            let result = program.alloc_register();
            resolver.with_plan_runtime_bindings(bindings, |resolver| {
                translate_plan_expr_no_constant_opt(
                    program,
                    None,
                    &expression,
                    result,
                    resolver,
                    NoConstantOptReason::RegisterReuse,
                )?;
                Ok(())
            })?;
            let passed = program.allocate_label();
            program.emit_insn(Insn::IsNull {
                reg: result,
                target_pc: passed,
            });
            program.emit_insn(Insn::If {
                reg: result,
                target_pc: passed,
                jump_if_null: false,
            });
            let name = constraint
                .name
                .clone()
                .unwrap_or_else(|| format!("{}_{}", definition.name, index));
            program.emit_insn(Insn::Halt {
                err_code: SQLITE_CONSTRAINT_CHECK,
                description: format!(
                    "value for domain {} violates check constraint \"{}\"",
                    definition.name, name
                ),
                on_error: None,
                description_reg: None,
            });
            program.preassign_label_to_next_insn(passed);
        }
    }
    Ok(())
}
