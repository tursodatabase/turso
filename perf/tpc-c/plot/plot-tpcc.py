def percentile(rt, n, percent):
    """The bucket where the running count passes the percentile; a bucket
    is named by its lower edge, so the answer is the bucket after it."""
    if n.sum() == 0:
        return 0.0
    seen = np.cumsum(n)
    i = int(np.searchsorted(seen, n.sum() * percent / 100.0))
    return float(rt[i] + 0.01)


