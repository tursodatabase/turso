//! The keywords that a name is quoted for when the AST is printed.

use turso_macros::match_ignore_ascii_case;

/// Defines `QUOTED_KEYWORDS` and `is_quotable_keyword` from one list.
macro_rules! quoted_keywords {
    ($($keyword:tt,)*) => {
        /// The keywords of the SQLite grammar that a name is quoted for.
        ///
        /// These are the keywords of the lexer of turso_parser, which this
        /// crate cannot use because turso_parser depends on it. `LATERAL` and
        /// `TYPE` are keywords of that lexer too, but a name that spells one
        /// of them is printed without quotes. A test in turso_parser checks
        /// that this list and the lexer agree.
        pub const QUOTED_KEYWORDS: &[&[u8]] = &[$($keyword),*];

        /// Whether `name` spells one of `QUOTED_KEYWORDS` (case-insensitive),
        /// so that it needs quotes when it is printed as a name.
        pub fn is_quotable_keyword(name: &[u8]) -> bool {
            match_ignore_ascii_case!(match name {
                $($keyword => true,)*
                _ => false,
            })
        }
    };
}

